// Tests for relative Markdown fragment links in the guides and repository documentation.

import assert from 'node:assert/strict'
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { afterEach, describe, test } from 'node:test'
import { checkGuideLinks } from './check-guide-links.ts'

const temporaryDirectories: string[] = []

async function fixture(files: Record<string, string>): Promise<string> {
  const root = await mkdtemp(path.join(tmpdir(), 'guide-links-'))
  temporaryDirectories.push(root)
  for (const [name, source] of Object.entries(files)) {
    const file = path.join(root, name)
    await mkdir(path.dirname(file), { recursive: true })
    await writeFile(file, source)
  }
  return root
}

afterEach(async () => {
  await Promise.all(temporaryDirectories.splice(0).map((dir) => rm(dir, { recursive: true, force: true })))
})

describe('checkGuideLinks', () => {
  test('accepts heading ids generated by rehype-slug', { timeout: 60_000 }, async () => {
    const root = await fixture({
      'docs/en/guide.md': [
        '[Editor plugins](editor.md#editor-plugins-492-898)',
        '[Scene tabs][scene-tabs]',
        '[Second repeated heading](editor.md#repeated-1)',
        '[External](https://example.com/missing.md#missing)',
        '[Same page](#not-checked-by-this-cross-page-check)',
        '',
        '[scene-tabs]: editor.md#场景标签页场景文件与未保存的修改866873',
      ].join('\n'),
      'docs/en/editor.md': [
        '## Editor plugins (#492, #898)',
        '## 场景标签页、场景文件与未保存的修改（#866，#873）',
        '## Repeated',
        '## Repeated',
      ].join('\n\n'),
    })

    assert.deepEqual(await checkGuideLinks(root), [])
  })

  test('fails on a relative link whose fragment matches no heading', { timeout: 60_000 }, async () => {
    const root = await fixture({
      'docs/zh/cli.md': '[编辑器插件](editor.md#编辑器插件492)',
      'docs/zh/editor.md': '## 编辑器插件（#492、#898）',
    })

    const problems = await checkGuideLinks(root)
    assert.equal(problems.length, 1)
    assert.match(problems[0]!, /docs\/zh\/cli\.md/)
    assert.match(problems[0]!, /编辑器插件492/)
    assert.match(problems[0]!, /docs\/zh\/editor\.md/)
  })

  test('checks both guide languages, skills, example READMEs and template READMEs', { timeout: 60_000 }, async () => {
    const source = '[Missing](target.md#missing)'
    const root = await fixture({
      'docs/en/source.md': source,
      'docs/zh/source.md': source,
      'skills/example/SKILL.md': source,
      'examples/example/README.md': source,
      'template/example/nested/README.md': source,
      'docs/en/target.md': '## Present',
      'docs/zh/target.md': '## Present',
      'skills/example/target.md': '## Present',
      'examples/example/target.md': '## Present',
      'template/example/nested/target.md': '## Present',
    })

    const problems = await checkGuideLinks(root)
    assert.equal(problems.length, 5)
    for (const file of ['docs/en/source.md', 'docs/zh/source.md', 'skills/example/SKILL.md', 'examples/example/README.md', 'template/example/nested/README.md']) {
      assert.ok(problems.some((problem) => problem.includes(file)), `no failure for ${file}`)
    }
  })

  test('checks the repository documentation', { timeout: 60_000 }, async () => {
    const root = path.resolve(import.meta.dirname, '../../..')
    assert.deepEqual(await checkGuideLinks(root), [])
  })
})

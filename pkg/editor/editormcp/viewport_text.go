type textAffine struct {
	a, b, c, d, e, f float64
}

func (m textAffine) mul(n textAffine) textAffine {
	return textAffine{
		a: m.a*n.a + m.c*n.b,
		b: m.b*n.a + m.d*n.b,
		c: m.a*n.c + m.c*n.d,
		d: m.b*n.c + m.d*n.d,
		e: m.a*n.e + m.c*n.f + m.e,
		f: m.b*n.e + m.d*n.f + m.f,
	}
}

func (m textAffine) apply(x, y float64) (float64, float64) {
	return m.a*x + m.c*y + m.e, m.b*x + m.d*y + m.f
}

// renderOverlayTextPNG replays DrawFillText operations from ops onto pngBytes using
// bitmapGlyph5x7 so viewport_image renders connection labels ("pulled → open"),
// camera bounds captions, and object labels legibly in the PNG returned to agents.
func renderOverlayTextPNG(pngBytes []byte, ops []core.DrawOp) ([]byte, bool) {
	src, err := png.Decode(bytes.NewReader(pngBytes))
	if err != nil {
		return pngBytes, false
	}
	b := src.Bounds()
	dst := image.NewRGBA(image.Rect(0, 0, b.Dx(), b.Dy()))
	draw.Draw(dst, dst.Bounds(), src, b.Min, draw.Src)

	type state struct {
		m     textAffine
		color core.Color
		alpha float64
	}
	cur := state{
		m:     textAffine{a: 1, d: 1},
		color: theme.Dark().TextPrimary,
		alpha: 1,
	}
	var stack []state
	drewAny := false

	for _, op := range ops {
		switch op.Kind {
		case core.DrawSave:
			stack = append(stack, cur)
		case core.DrawRestore:
			if n := len(stack); n > 0 {
				cur = stack[n-1]
				stack = stack[:n-1]
			}
		case core.DrawTranslate:
			cur.m = cur.m.mul(textAffine{a: 1, d: 1, e: float64(op.X), f: float64(op.Y)})
		case core.DrawScale:
			cur.m = cur.m.mul(textAffine{a: float64(op.X), d: float64(op.Y)})
		case core.DrawRotate:
			sn, cs := math.Sincos(float64(op.A))
			cur.m = cur.m.mul(textAffine{a: cs, b: sn, c: -sn, d: cs})
		case core.DrawTransform:
			cur.m = cur.m.mul(textAffine{
				a: float64(op.X1), b: float64(op.Y1),
				c: float64(op.X2), d: float64(op.Y2),
				e: float64(op.X), f: float64(op.Y),
			})
		case core.DrawSetTransform:
			cur.m = textAffine{
				a: float64(op.X1), b: float64(op.Y1),
				c: float64(op.X2), d: float64(op.Y2),
				e: float64(op.X), f: float64(op.Y),
			}
		case core.DrawFillColor:
			cur.color = op.Color
		case core.DrawAlpha:
			cur.alpha = min(max(float64(op.A), 0), 1)
		case core.DrawFillText:
			if op.Text == "" {
				continue
			}
			px, py := cur.m.apply(float64(op.X), float64(op.Y))
			scale := math.Sqrt(math.Hypot(cur.m.a, cur.m.b) * math.Hypot(cur.m.c, cur.m.d))
			if math.IsNaN(px) || math.IsInf(px, 0) || math.IsNaN(py) || math.IsInf(py, 0) || math.IsNaN(scale) || math.IsInf(scale, 0) {
				continue
			}
			if math.Abs(px) > 1e7 || math.Abs(py) > 1e7 {
				continue
			}
			if scale < 1 {
				scale = 1
			} else if scale > maxOverlayTextPixScale {
				scale = maxOverlayTextPixScale
			}
			pixScale := int(math.Round(scale))
			// FillText uses (x, y) as baseline; lift by glyph height (~7*pixScale) so text sits cleanly inside pills.
			ox := int(math.Round(px))
			oy := int(math.Round(py)) - 7*pixScale
			drawBitmapString(dst, ox, oy, op.Text, cur.color, cur.alpha, pixScale)
			drewAny = true
		}
	}
	if !drewAny {
		return pngBytes, false
	}
	var out bytes.Buffer
	if err := png.Encode(&out, dst); err != nil {
		return pngBytes, false
	}
	return out.Bytes(), true
}

func drawBitmapString(dst *image.RGBA, x, y int, text string, col core.Color, alpha float64, scale int) {
	a := float64(col&0xFF) / 255.0 * alpha
	if a <= 0 {
		return
	}
	r := float64((col>>24)&0xFF) / 255.0
	g := float64((col>>16)&0xFF) / 255.0
	b := float64((col>>8)&0xFF) / 255.0
	sr, sg, sb, sa := r*a, g*a, b*a, a

	bounds := dst.Bounds()
	cx := x
	for _, ch := range text {
		glyph, ok := bitmapGlyph5x7[ch]
		if !ok {
			if ch >= 'a' && ch <= 'z' {
				glyph = bitmapGlyph5x7[ch-'a'+'A']
			} else {
				glyph = bitmapGlyph5x7[' ']
			}
		}
		for row := range 7 {
			bits := glyph[row]
			for colIdx := range 5 {
				if bits&(1<<(4-colIdx)) == 0 {
					continue
				}
				for sy := range scale {
					py := y + row*scale + sy
					if py < bounds.Min.Y || py >= bounds.Max.Y {
						continue
					}
					for sx := range scale {
						px := cx + colIdx*scale + sx
						if px < bounds.Min.X || px >= bounds.Max.X {
							continue
						}
						off := (py-bounds.Min.Y)*dst.Stride + (px-bounds.Min.X)*4
						inv := 1 - sa
						dr := float64(dst.Pix[off])/255.0*inv + sr
						dg := float64(dst.Pix[off+1])/255.0*inv + sg
						db := float64(dst.Pix[off+2])/255.0*inv + sb
						da := float64(dst.Pix[off+3])/255.0*inv + sa
						dst.Pix[off] = uint8(min(max(math.Round(dr*255), 0), 255))
						dst.Pix[off+1] = uint8(min(max(math.Round(dg*255), 0), 255))
						dst.Pix[off+2] = uint8(min(max(math.Round(db*255), 0), 255))
						dst.Pix[off+3] = uint8(min(max(math.Round(da*255), 0), 255))
					}
				}
			}
		}
		cx += 6 * scale
	}
}

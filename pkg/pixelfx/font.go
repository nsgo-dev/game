// Glyph is one character of a pixel font: W columns, and the rows of its inked pixels.
type Glyph struct {
	W    int
	Rows [][]bool
}

// Font is a pixel font: H rows tall, Space wide for a character it lacks, Gap between characters.
type Font struct {
	H, Space, Gap int
	Glyphs        map[rune]Glyph
}

func buildFont(table map[rune]string, h int) map[rune]Glyph {
	out := make(map[rune]Glyph, len(table))
	for ch, src := range table {
		rows := strings.Split(src, "|")
		if len(rows) != h {
			panic("pixelfx: glyph " + string(ch) + " has the wrong number of rows")
		}
		g := Glyph{W: len(rows[0]), Rows: make([][]bool, len(rows))}
		for i, r := range rows {
			g.Rows[i] = make([]bool, len(r))
			for j := range r {
				g.Rows[i][j] = r[j] == '#'
			}
		}
		out[ch] = g
	}
	return out
}

// Fonts are pixelfx's two in-code pixel fonts, "mini" (3x5) and "big" (5x7).
var Fonts = map[string]*Font{
	"mini": {H: 5, Space: 2, Gap: 1, Glyphs: buildFont(miniGlyphs, 5)},
	"big":  {H: 7, Space: 3, Gap: 1, Glyphs: buildFont(bigGlyphs, 7)},
}

func (f *Font) glyph(ch rune) (Glyph, bool) {
	if g, ok := f.Glyphs[ch]; ok {
		return g, true
	}
	g, ok := f.Glyphs[unicode.ToUpper(ch)]
	return g, ok
}

// TextWidth returns the width in font pixels of str set in font ("mini" or "big"), before scaling.
func TextWidth(str, font string) int {
	F := Fonts[font]
	w := 0
	for _, ch := range str {
		if g, ok := F.glyph(ch); ok {
			w += g.W + F.Gap
		} else {
			w += F.Space + F.Gap
		}
	}
	return max(0, w-F.Gap)
}

// rasterText calls plot(x, y) for every inked font pixel of str, with the top-left of the text at (0, 0).
func rasterText(str, font string, plot func(x, y int)) {
	F := Fonts[font]
	x := 0
	for _, ch := range str {
		g, ok := F.glyph(ch)
		if !ok {
			x += F.Space + F.Gap
			continue
		}
		for r := 0; r < F.H; r++ {
			for c := 0; c < g.W; c++ {
				if g.Rows[r][c] {
					plot(x+c, r)
				}
			}
		}
		x += g.W + F.Gap
	}
}

// RasterText calls plot(x, y) for every inked pixel of str set in font ("mini" or "big"), with the top-left of the text at (0, 0).
func RasterText(str, font string, plot func(x, y int)) { rasterText(str, font, plot) }

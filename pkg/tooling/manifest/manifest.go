// Package manifest walks an assets directory and generates a typed Go source file referencing every asset, so missing or removed assets fail the build at compile time.
package manifest

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"go/token"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"unicode"

	"github.com/nsgo-dev/game/pkg/importsettings"
)

const (
	defaultPackage = "assets"
	defaultPrefix  = "asset:"
	defaultHeader  = "// Code generated by game manifest. DO NOT EDIT."
)

// Kind classifies a discovered asset file by its extension.
type Kind int

const (
	// KindOther is any asset that is not an image, audio or map file.
	KindOther Kind = iota
	// KindImage is an image file exposed as a core.ImageSource.
	KindImage
	// KindAudio is an audio file exposed as an audio.Source.
	KindAudio
	// KindMap is a tilemap file (.tmj, .tmx, .tsj, .tsx).
	KindMap
)

// String returns the kind's name.
func (k Kind) String() string {
	switch k {
	case KindImage:
		return "image"
	case KindAudio:
		return "audio"
	case KindMap:
		return "map"
	default:
		return "other"
	}
}

// Entry is one asset file discovered in the assets directory.
type Entry struct {
	// Path is the asset's slash-separated path relative to the scanned directory.
	Path string
	// URI is the asset's URI with the configured prefix, such as "asset:hero.png".
	URI string
	// Ident is the exported Go identifier generated for this asset, such as "ImageHero".
	Ident string
	// Kind is the asset's classified type.
	Kind Kind
}

// Options configures asset scanning and Go source generation.
type Options struct {
	// Package is the generated Go file's package name ("assets" when empty).
	Package string
	// Prefix is prepended to each asset's relative path to form its URI ("asset:" when empty).
	Prefix string
	// Embed emits //go:embed directives so asset bytes are compiled into the binary instead of referencing URIs.
	Embed bool
	// EmbedDir is an optional slash-separated directory prefix prepended to each //go:embed pattern, for when the generated file lives in a parent of the assets directory.
	EmbedDir string
	// Header is the comment line at the top of the generated file (a standard generated-file notice when empty).
	Header string
}

// DefaultOptions returns Options with the generator's defaults: package "assets", URI prefix "asset:" and URI mode.
func DefaultOptions() Options {
	return Options{
		Package: defaultPackage,
		Prefix:  defaultPrefix,
		Header:  defaultHeader,
	}
}

// Scan walks dir deterministically, skipping dot-prefixed entries, Go source files and import settings sidecars (files named *.import.yaml, as package importsettings names them), and returns the discovered asset entries sorted by Path with unique Go identifiers.
func Scan(dir string, opts Options) ([]Entry, error) {
	cfg, err := normalizeOptions(opts)
	if err != nil {
		return nil, err
	}
	info, err := os.Stat(dir)
	if err != nil {
		return nil, fmt.Errorf("manifest: %w", err)
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("manifest: %q is not a directory", dir)
	}

	var relPaths []string
	err = filepath.WalkDir(dir, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if d.IsDir() {
			if p != dir && strings.HasPrefix(d.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		// Import settings and generated asset source sidecars describe how an asset is built or where it came from; the game never loads them.
		if strings.HasPrefix(d.Name(), ".") || strings.EqualFold(filepath.Ext(d.Name()), ".go") || importsettings.IsSidecar(d.Name()) || importsettings.IsAssetSource(d.Name()) {
			return nil
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		relPaths = append(relPaths, filepath.ToSlash(rel))
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("manifest: walk %q: %w", dir, err)
	}
	slices.Sort(relPaths)

	entries := make([]Entry, len(relPaths))
	for i, rel := range relPaths {
		kind := classifyExt(path.Ext(rel))
		entries[i] = Entry{
			Path: rel,
			URI:  cfg.Prefix + rel,
			Kind: kind,
		}
	}
	assignIdents(entries)
	return entries, nil
}

// Generate scans dir and returns a gofmt-formatted Go source file declaring typed references for every asset in dir.
func Generate(dir string, opts Options) ([]byte, error) {
	cfg, err := normalizeOptions(opts)
	if err != nil {
		return nil, err
	}
	entries, err := Scan(dir, cfg)
	if err != nil {
		return nil, err
	}
	return formatEntries(entries, cfg)
}

// WriteFile generates the manifest for dir and writes it to outPath, creating parent directories if needed.
func WriteFile(dir, outPath string, opts Options) error {
	src, err := Generate(dir, opts)
	if err != nil {
		return err
	}
	if parent := filepath.Dir(outPath); parent != "" && parent != "." {
		if err := os.MkdirAll(parent, 0o755); err != nil {
			return fmt.Errorf("manifest: create output dir: %w", err)
		}
	}
	if err := os.WriteFile(outPath, src, 0o644); err != nil {
		return fmt.Errorf("manifest: write %s: %w", outPath, err)
	}
	return nil
}

// Verify checks that every asset reference in refs exists as a regular file under dir.
// Each ref may be a relative path ("hero.png") or an "asset:" URI ("asset:hero.png").
func Verify(dir string, refs []string) error {
	info, err := os.Stat(dir)
	if err != nil {
		return fmt.Errorf("manifest: %w", err)
	}
	if !info.IsDir() {
		return fmt.Errorf("manifest: %q is not a directory", dir)
	}

	var problems []string
	for _, ref := range refs {
		rel := strings.TrimPrefix(ref, defaultPrefix)
		if rel == "" || strings.HasPrefix(rel, "/") || filepath.IsAbs(rel) {
			problems = append(problems, fmt.Sprintf("%q (invalid path)", ref))
			continue
		}
		cleaned := path.Clean(filepath.ToSlash(rel))
		if cleaned == "." || cleaned == ".." || strings.HasPrefix(cleaned, "../") {
			problems = append(problems, fmt.Sprintf("%q (escapes assets directory)", ref))
			continue
		}
		full := filepath.Join(dir, filepath.FromSlash(cleaned))
		st, err := os.Stat(full)
		if err != nil {
			problems = append(problems, fmt.Sprintf("%q (missing)", ref))
			continue
		}
		if st.IsDir() {
			problems = append(problems, fmt.Sprintf("%q (is a directory)", ref))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("manifest: missing or invalid assets in %q: %s", dir, strings.Join(problems, ", "))
	}
	return nil
}

func normalizeOptions(opts Options) (Options, error) {
	if opts.Package == "" {
		opts.Package = defaultPackage
	}
	if !token.IsIdentifier(opts.Package) || token.IsKeyword(opts.Package) {
		return Options{}, fmt.Errorf("manifest: invalid Go package name %q", opts.Package)
	}
	if opts.Prefix == "" {
		opts.Prefix = defaultPrefix
	}
	if opts.Header == "" {
		opts.Header = defaultHeader
	}
	if opts.EmbedDir != "" {
		clean := path.Clean(filepath.ToSlash(opts.EmbedDir))
		if clean == "." {
			opts.EmbedDir = ""
		} else if strings.HasPrefix(clean, "/") || clean == ".." || strings.HasPrefix(clean, "../") {
			return Options{}, fmt.Errorf("manifest: invalid embed dir %q", opts.EmbedDir)
		} else {
			opts.EmbedDir = clean
		}
	}
	return opts, nil
}

func classifyExt(ext string) Kind {
	switch strings.ToLower(ext) {
	case ".png", ".jpg", ".jpeg", ".webp", ".gif", ".bmp", ".avif", ".svg":
		return KindImage
	case ".wav", ".mp3", ".m4a", ".aac", ".ogg", ".flac", ".opus":
		return KindAudio
	case ".tmj", ".tmx", ".tsj", ".tsx":
		return KindMap
	default:
		return KindOther
	}
}

func kindPrefix(k Kind) string {
	switch k {
	case KindImage:
		return "Image"
	case KindAudio:
		return "Sound"
	case KindMap:
		return "Map"
	default:
		return "Asset"
	}
}

func assignIdents(entries []Entry) {
	baseCount := make(map[string]int, len(entries))
	bases := make([]string, len(entries))
	for i, e := range entries {
		ext := path.Ext(e.Path)
		stem := strings.TrimSuffix(e.Path, ext)
		name := pascalWords(stem)
		if name == "" {
			name = "File"
		}
		bases[i] = kindPrefix(e.Kind) + name
		baseCount[bases[i]]++
	}

	candidates := make([]string, len(entries))
	for i, e := range entries {
		id := bases[i]
		if baseCount[id] > 1 {
			ext := strings.TrimPrefix(path.Ext(e.Path), ".")
			if suffix := pascalWords(ext); suffix != "" {
				id += suffix
			}
		}
		candidates[i] = id
	}

	used := map[string]bool{"All": true}
	for i := range entries {
		id := candidates[i]
		if !used[id] {
			entries[i].Ident = id
			used[id] = true
			continue
		}
		for n := 2; ; n++ {
			alt := id + strconv.Itoa(n)
			if !used[alt] {
				entries[i].Ident = alt
				used[alt] = true
				break
			}
		}
	}
}

// pascalWords turns a path or stem into a PascalCase identifier fragment, splitting on non-alphanumeric characters and uppercasing the first rune of each word.
func pascalWords(s string) string {
	var b strings.Builder
	newWord := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) {
			newWord = true
			continue
		}
		if newWord {
			b.WriteRune(unicode.ToUpper(r))
			newWord = false
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func unexportedDataVar(ident string) string {
	if ident == "" {
		return "assetData"
	}
	runes := []rune(ident)
	runes[0] = unicode.ToLower(runes[0])
	return string(runes) + "Data"
}

func formatEmbedPattern(embedDir, rel string) string {
	p := rel
	if embedDir != "" {
		p = path.Join(embedDir, rel)
	}
	for _, r := range p {
		if unicode.IsSpace(r) || r == '"' || r == '`' || r == '\\' {
			return strconv.Quote(p)
		}
	}
	return p
}

func formatEntries(entries []Entry, cfg Options) ([]byte, error) {
	var hasImage, hasAudio bool
	for _, e := range entries {
		switch e.Kind {
		case KindImage:
			hasImage = true
		case KindAudio:
			hasAudio = true
		}
	}

	sortedByIdent := slices.Clone(entries)
	slices.SortFunc(sortedByIdent, func(a, b Entry) int { return cmp.Compare(a.Ident, b.Ident) })

	var buf bytes.Buffer
	fmt.Fprintln(&buf, cfg.Header)
	fmt.Fprintln(&buf)
	fmt.Fprintf(&buf, "package %s\n", cfg.Package)

	needEmbed := cfg.Embed && len(entries) > 0
	if needEmbed || hasImage || hasAudio {
		fmt.Fprintln(&buf)
		fmt.Fprintln(&buf, "import (")
		if needEmbed {
			fmt.Fprintln(&buf, "\t_ \"embed\"")
			if hasImage || hasAudio {
				fmt.Fprintln(&buf)
			}
		}
		if hasAudio {
			fmt.Fprintln(&buf, "\t\"github.com/nsgo-dev/nsgo/audio\"")
		}
		if hasImage {
			fmt.Fprintln(&buf, "\t\"github.com/nsgo-dev/nsgo/core\"")
		}
		fmt.Fprintln(&buf, ")")
	}

	if cfg.Embed {
		if len(sortedByIdent) > 0 {
			fmt.Fprintln(&buf)
		}
		for _, e := range sortedByIdent {
			pat := formatEmbedPattern(cfg.EmbedDir, e.Path)
			switch e.Kind {
			case KindImage, KindAudio:
				fmt.Fprintf(&buf, "//go:embed %s\nvar %s []byte\n\n", pat, unexportedDataVar(e.Ident))
			default:
				fmt.Fprintf(&buf, "//go:embed %s\nvar %s []byte\n\n", pat, e.Ident)
			}
		}
		var sources []Entry
		for _, e := range sortedByIdent {
			if e.Kind == KindImage || e.Kind == KindAudio {
				sources = append(sources, e)
			}
		}
		if len(sources) > 0 {
			fmt.Fprintln(&buf, "var (")
			for _, e := range sources {
				switch e.Kind {
				case KindImage:
					fmt.Fprintf(&buf, "\t%s = core.ImageSource{Data: %s}\n", e.Ident, unexportedDataVar(e.Ident))
				case KindAudio:
					fmt.Fprintf(&buf, "\t%s = audio.Source{Data: %s}\n", e.Ident, unexportedDataVar(e.Ident))
				}
			}
			fmt.Fprintln(&buf, ")")
		}
	} else {
		var sources, consts []Entry
		for _, e := range sortedByIdent {
			if e.Kind == KindImage || e.Kind == KindAudio {
				sources = append(sources, e)
			} else {
				consts = append(consts, e)
			}
		}
		if len(sources) > 0 {
			fmt.Fprintln(&buf)
			fmt.Fprintln(&buf, "var (")
			for _, e := range sources {
				switch e.Kind {
				case KindImage:
					fmt.Fprintf(&buf, "\t%s = core.ImageSource{URI: %q}\n", e.Ident, e.URI)
				case KindAudio:
					fmt.Fprintf(&buf, "\t%s = audio.Source{URI: %q}\n", e.Ident, e.URI)
				}
			}
			fmt.Fprintln(&buf, ")")
		}
		if len(consts) > 0 {
			fmt.Fprintln(&buf)
			fmt.Fprintln(&buf, "const (")
			for _, e := range consts {
				fmt.Fprintf(&buf, "\t%s = %q\n", e.Ident, e.URI)
			}
			fmt.Fprintln(&buf, ")")
		}
	}

	fmt.Fprintln(&buf)
	fmt.Fprintln(&buf, "// All lists every asset URI discovered in the assets directory.")
	if len(entries) == 0 {
		fmt.Fprintln(&buf, "var All = []string{}")
	} else {
		fmt.Fprintln(&buf, "var All = []string{")
		for _, e := range entries {
			fmt.Fprintf(&buf, "\t%q,\n", e.URI)
		}
		fmt.Fprintln(&buf, "}")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("manifest: format generated source: %w", err)
	}
	return formatted, nil
}

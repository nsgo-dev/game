package wire

import (
	"bytes"
	"fmt"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

// DefaultTSRuntimeImport is the ES module specifier imported by generated TypeScript codecs when EmbedRuntime is false.
const DefaultTSRuntimeImport = "./runtime.ts"

// NamedSchema pairs a parsed wire Schema with its schema file name (for example "transport.wire.yaml") so cross-file TypeScript imports resolve to sibling generated modules.
type NamedSchema struct {
	Name   string
	Schema *Schema
}

// TSGenerateOptions configures TypeScript codec generation in GenerateTS.
type TSGenerateOptions struct {
	// SourceName is the schema file name shown in the generated header comment.
	SourceName string
	// RuntimeImport overrides DefaultTSRuntimeImport when EmbedRuntime is false.
	RuntimeImport string
	// EmbedRuntime embeds the shared runtime directly into the generated module instead of importing RuntimeImport.
	EmbedRuntime bool
	// ExtraSchemas supplies sibling schemas referenced via imports, paired with their schema file names.
	ExtraSchemas []NamedSchema
}

// TSOutputFileName returns the generated TypeScript file name for a *.wire.yaml schema file name (for example "replication.wire.yaml" -> "replication_wire.ts").
func TSOutputFileName(schemaBaseName string) string {
	stem := strings.TrimSuffix(schemaBaseName, ".wire.yaml")
	if stem == schemaBaseName {
		stem = strings.TrimSuffix(schemaBaseName, filepath.Ext(schemaBaseName))
	}
	return stem + "_wire.ts"
}

// GenerateTSIndex generates a deterministic barrel index.ts re-exporting runtime.ts and each generated schema module.
func GenerateTSIndex(schemaFileNames []string) []byte {
	sorted := slices.Clone(schemaFileNames)
	slices.Sort(sorted)
	var out bytes.Buffer
	out.WriteString("// Code generated by game wire; DO NOT EDIT.\n\n")
	out.WriteString("export * from \"./runtime.ts\";\n")
	for _, name := range sorted {
		fmt.Fprintf(&out, "export * from \"./%s\";\n", TSOutputFileName(name))
	}
	return out.Bytes()
}

// GenerateTS generates deterministic, dependency-free TypeScript codec source for schema.
func GenerateTS(schema *Schema, opts TSGenerateOptions) ([]byte, error) {
	if schema == nil {
		return nil, fmt.Errorf("wire: ts codegen: schema is nil")
	}
	all := make([]*Schema, 0, 1+len(opts.ExtraSchemas))
	all = append(all, schema)
	for _, extra := range opts.ExtraSchemas {
		all = append(all, extra.Schema)
	}
	if err := ValidateAll(all); err != nil {
		return nil, err
	}

	env := newTypeEnv()
	localTypes := make(map[string]bool)
	typeModules := make(map[string]string)

	for _, en := range schema.Enums {
		env.enums[en.Name] = en
		localTypes[en.Name] = true
	}
	for _, m := range schema.Messages {
		env.messages[m.Name] = m
		localTypes[m.Name] = true
	}
	for _, u := range schema.Unions {
		env.unions[u.Name] = u
		localTypes[u.Name] = true
	}
	for _, extra := range opts.ExtraSchemas {
		modPath := "./" + TSOutputFileName(extra.Name)
		for _, en := range extra.Schema.Enums {
			env.enums[en.Name] = en
			typeModules[en.Name] = modPath
		}
		for _, m := range extra.Schema.Messages {
			env.messages[m.Name] = m
			typeModules[m.Name] = modPath
		}
		for _, u := range extra.Schema.Unions {
			env.unions[u.Name] = u
			typeModules[u.Name] = modPath
		}
	}

	runtimeImport := opts.RuntimeImport
	if runtimeImport == "" {
		runtimeImport = DefaultTSRuntimeImport
	}

	g := &tsGen{
		schema:        schema,
		env:           env,
		localTypes:    localTypes,
		typeModules:   typeModules,
		embedRuntime:  opts.EmbedRuntime,
		runtimeImport: runtimeImport,
		rtTypes:       make(map[string]bool),
		rtValues:      make(map[string]bool),
		extTypes:      make(map[string]map[string]bool),
		extValues:     make(map[string]map[string]bool),
		minWireSizes:  make(map[string]int),
	}

	var body bytes.Buffer
	for _, en := range schema.Enums {
		g.emitEnum(&body, en)
	}
	for _, m := range schema.Messages {
		g.emitMessage(&body, m)
	}
	for _, u := range schema.Unions {
		g.emitUnion(&body, u)
	}

	var out bytes.Buffer
	if opts.SourceName != "" {
		fmt.Fprintf(&out, "// Code generated by game wire from %s; DO NOT EDIT.\n\n", opts.SourceName)
	} else {
		out.WriteString("// Code generated by game wire; DO NOT EDIT.\n\n")
	}

	if opts.EmbedRuntime {
		g.emitExternalImports(&out)
		out.WriteString(tsRuntimeBody)
		out.WriteByte('\n')
	} else {
		g.emitRuntimeImport(&out)
		g.emitExternalImports(&out)
	}
	out.Write(body.Bytes())
	return out.Bytes(), nil
}

type tsGen struct {
	schema        *Schema
	env           *typeEnv
	localTypes    map[string]bool
	typeModules   map[string]string
	embedRuntime  bool
	runtimeImport string
	rtTypes       map[string]bool
	rtValues      map[string]bool
	extTypes      map[string]map[string]bool
	extValues     map[string]map[string]bool
	minWireSizes  map[string]int
}

func (g *tsGen) useRTType(sym string) {
	g.rtTypes[sym] = true
}

func (g *tsGen) useRTValue(sym string) {
	g.rtValues[sym] = true
}

func (g *tsGen) useExtType(typeName string) {
	if g.localTypes[typeName] {
		return
	}
	mod, ok := g.typeModules[typeName]
	if !ok {
		return
	}
	if g.extTypes[mod] == nil {
		g.extTypes[mod] = make(map[string]bool)
	}
	g.extTypes[mod][typeName] = true
}

func (g *tsGen) useExtValue(typeName, sym string) {
	if g.localTypes[typeName] {
		return
	}
	mod, ok := g.typeModules[typeName]
	if !ok {
		return
	}
	if g.extValues[mod] == nil {
		g.extValues[mod] = make(map[string]bool)
	}
	g.extValues[mod][sym] = true
}

func (g *tsGen) emitRuntimeImport(out *bytes.Buffer) {
	if len(g.rtTypes) == 0 && len(g.rtValues) == 0 {
		return
	}
	var specs []string
	var vals []string
	for s := range g.rtValues {
		vals = append(vals, s)
	}
	slices.Sort(vals)
	for _, s := range vals {
		specs = append(specs, s)
	}
	var types []string
	for s := range g.rtTypes {
		if !g.rtValues[s] {
			types = append(types, s)
		}
	}
	slices.Sort(types)
	for _, s := range types {
		specs = append(specs, "type "+s)
	}
	fmt.Fprintf(out, "import { %s } from %q;\n", strings.Join(specs, ", "), g.runtimeImport)
	if len(g.extTypes) == 0 && len(g.extValues) == 0 {
		out.WriteByte('\n')
	}
}

func (g *tsGen) emitExternalImports(out *bytes.Buffer) {
	modsMap := make(map[string]bool)
	for mod := range g.extTypes {
		modsMap[mod] = true
	}
	for mod := range g.extValues {
		modsMap[mod] = true
	}
	if len(modsMap) == 0 {
		return
	}
	var mods []string
	for mod := range modsMap {
		mods = append(mods, mod)
	}
	slices.Sort(mods)
	for _, mod := range mods {
		var specs []string
		var vals []string
		for s := range g.extValues[mod] {
			vals = append(vals, s)
		}
		slices.Sort(vals)
		for _, s := range vals {
			specs = append(specs, s)
		}
		var types []string
		for s := range g.extTypes[mod] {
			if !g.extValues[mod][s] {
				types = append(types, s)
			}
		}
		slices.Sort(types)
		for _, s := range types {
			specs = append(specs, "type "+s)
		}
		fmt.Fprintf(out, "import { %s } from %q;\n", strings.Join(specs, ", "), mod)
	}
	out.WriteByte('\n')
}

func (g *tsGen) effectiveOrder(orders ...ByteOrder) ByteOrder {
	for _, o := range orders {
		if o != "" {
			return o
		}
	}
	if g.schema.Order != "" {
		return g.schema.Order
	}
	return OrderBig
}

func tsLEBool(o ByteOrder) string {
	if o == OrderLittle {
		return "true"
	}
	return "false"
}

func isTSBigIntWireType(wireType string, bits int) bool {
	switch wireType {
	case "u64", "i64":
		return true
	case "uvarint", "svarint":
		return bits == 0 || bits == 64
	case "bits":
		return bits > 32
	default:
		return false
	}
}

func (g *tsGen) tsTypeForWire(wireType string, bits int) string {
	switch wireType {
	case "u8", "u16", "u32", "i8", "i16", "i32", "f32", "qfloat", "fixed":
		return "number"
	case "u64", "i64":
		return "bigint"
	case "uvarint", "svarint":
		if isTSBigIntWireType(wireType, bits) {
			return "bigint"
		}
		return "number"
	case "bits":
		if bits > 32 {
			return "bigint"
		}
		return "number"
	case "bool":
		return "boolean"
	case "bytes":
		return "Uint8Array"
	case "string":
		return "string"
	default:
		g.useExtType(wireType)
		return wireType
	}
}

func (g *tsGen) tsTypeForField(f Field) string {
	if f.Type == "array" {
		if f.Array.Count > 0 && f.Array.Of == "u8" {
			return "Uint8Array"
		}
		return g.tsTypeForWire(f.Array.Of, f.Array.OfBits) + "[]"
	}
	return g.tsTypeForWire(f.Type, f.Bits)
}

func (g *tsGen) tsZeroExprForField(f Field) string {
	switch f.Type {
	case "u8", "u16", "u32", "i8", "i16", "i32", "f32", "qfloat", "fixed":
		return "0"
	case "u64", "i64":
		return "0n"
	case "uvarint", "svarint":
		if isTSBigIntWireType(f.Type, f.Bits) {
			return "0n"
		}
		return "0"
	case "bits":
		if f.Bits > 32 {
			return "0n"
		}
		return "0"
	case "bool":
		return "false"
	case "bytes":
		g.useRTValue("EMPTY_BYTES")
		return "EMPTY_BYTES"
	case "string":
		return `""`
	case "array":
		if f.Array.Count > 0 {
			if f.Array.Of == "u8" {
				return fmt.Sprintf("new Uint8Array(%d)", f.Array.Count)
			}
			elemZero := g.tsZeroExprForElem(f.Array.Of, f.Array.OfBits)
			if _, isMsg := g.env.messages[f.Array.Of]; isMsg {
				return fmt.Sprintf("Array.from({ length: %d }, () => %s)", f.Array.Count, elemZero)
			}
			return fmt.Sprintf("new Array(%d).fill(%s)", f.Array.Count, elemZero)
		}
		return "[]"
	default:
		if en, ok := g.env.enums[f.Type]; ok {
			g.useExtValue(en.Name, en.Name)
			return fmt.Sprintf("%s.%s", en.Name, toExportedIdent(en.Values[0].Name))
		}
		g.useExtValue(f.Type, "create"+f.Type)
		return fmt.Sprintf("create%s()", f.Type)
	}
}

func (g *tsGen) tsZeroExprForElem(elemType string, elemBits int) string {
	switch elemType {
	case "u8", "u16", "u32", "i8", "i16", "i32", "f32":
		return "0"
	case "u64", "i64":
		return "0n"
	case "uvarint", "svarint":
		if isTSBigIntWireType(elemType, elemBits) {
			return "0n"
		}
		return "0"
	case "bool":
		return "false"
	default:
		if en, ok := g.env.enums[elemType]; ok {
			g.useExtValue(en.Name, en.Name)
			return fmt.Sprintf("%s.%s", en.Name, toExportedIdent(en.Values[0].Name))
		}
		g.useExtValue(elemType, "create"+elemType)
		return fmt.Sprintf("create%s()", elemType)
	}
}

func (g *tsGen) isBitPacked(f Field, msgOrder ByteOrder) bool {
	if f.Type == "bits" {
		return true
	}
	if f.Type == "qfloat" {
		ord := g.effectiveOrder(f.Order, msgOrder)
		if ord == OrderLittle && (f.QFloat.Bits == 8 || f.QFloat.Bits == 16 || f.QFloat.Bits == 32) {
			return false
		}
		return true
	}
	return false
}

func tsIntLiteral(v uint64, big bool) string {
	if big {
		return strconv.FormatUint(v, 10) + "n"
	}
	return strconv.FormatUint(v, 10)
}

func tsHexLiteral(v uint64, big bool) string {
	if big {
		return fmt.Sprintf("0x%xn", v)
	}
	return fmt.Sprintf("0x%x", v)
}

func (g *tsGen) emitEnum(b *bytes.Buffer, en Enum) {
	isBig := isTSBigIntWireType(en.Type, 0)
	baseTSType := "number"
	if isBig {
		baseTSType = "bigint"
	}
	g.useRTType("Writer")
	g.useRTType("Reader")
	g.useRTValue("WireError")

	if en.Doc != "" {
		writeDocComment(b, "", en.Doc)
	}
	fmt.Fprintf(b, "export const %s = {\n", en.Name)
	for _, v := range en.Values {
		if v.Doc != "" {
			writeDocComment(b, "  ", v.Doc)
		}
		fmt.Fprintf(b, "  %s: %s,\n", toExportedIdent(v.Name), tsIntLiteral(v.Value, isBig))
	}
	b.WriteString("} as const;\n")
	fmt.Fprintf(b, "export type %s = (typeof %s)[keyof typeof %s];\n\n", en.Name, en.Name, en.Name)

	fmt.Fprintf(b, "export function isValid%s(v: %s): v is %s {\n  switch (v) {\n", en.Name, baseTSType, en.Name)
	for _, v := range en.Values {
		fmt.Fprintf(b, "    case %s.%s:\n", en.Name, toExportedIdent(v.Name))
	}
	b.WriteString("      return true;\n    default:\n      return false;\n  }\n}\n\n")

	ord := g.effectiveOrder(en.Order)
	fmt.Fprintf(b, "export function encode%s(v: %s, w: Writer): void {\n", en.Name, en.Name)
	g.emitWriteInt(b, "  ", en.Type, ord, 0, "v")
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "export function decode%s(r: Reader): %s {\n", en.Name, en.Name)
	fmt.Fprintf(b, "  const raw = %s;\n", g.readIntExpr(en.Type, ord, 0))
	fmt.Fprintf(b, "  if (!isValid%s(raw)) {\n    throw new WireError(\"invalid_enum\", \"wire: unknown enum value\");\n  }\n  return raw;\n}\n\n", en.Name)
}

func (g *tsGen) emitMessage(b *bytes.Buffer, m Message) {
	// Emit constants for const fields and mask groups.
	hasConsts := false
	for _, f := range m.Fields {
		if f.Const != nil {
			hasConsts = true
			if en, isEnum := g.env.enums[f.Type]; isEnum {
				isBig := isTSBigIntWireType(en.Type, 0)
				fmt.Fprintf(b, "export const %s%s = %s;\n", m.Name, toExportedIdent(f.Name), tsIntLiteral(*f.Const, isBig))
			} else {
				isBig := isTSBigIntWireType(f.Type, f.Bits)
				fmt.Fprintf(b, "export const %s%s = %s;\n", m.Name, toExportedIdent(f.Name), tsIntLiteral(*f.Const, isBig))
			}
		}
		if f.Type == "mask" {
			hasConsts = true
			maskType := f.Mask.Type
			if maskType == "" {
				maskType = "u8"
			}
			isBig := maskType == "u64"
			var validMask uint64
			for i, sf := range f.Mask.Fields {
				bit := uint64(1) << i
				validMask |= bit
				fmt.Fprintf(b, "export const %sField%s = %s;\n", m.Name, toExportedIdent(sf.Name), tsHexLiteral(bit, isBig))
			}
			fmt.Fprintf(b, "export const %sMaskValid = %s;\n", m.Name, tsHexLiteral(validMask, isBig))
		}
	}
	if hasConsts {
		b.WriteByte('\n')
	}

	if m.Doc != "" {
		writeDocComment(b, "", m.Doc)
	}
	fmt.Fprintf(b, "export interface %s {\n", m.Name)
	nonConstCount := 0
	for _, f := range m.Fields {
		if f.Const != nil {
			continue
		}
		nonConstCount++
		if f.Type == "mask" {
			maskType := f.Mask.Type
			if maskType == "" {
				maskType = "u8"
			}
			if f.Doc != "" {
				writeDocComment(b, "  ", f.Doc)
			}
			fmt.Fprintf(b, "  %sMask: %s;\n", toTSFieldName(f.Name), g.tsTypeForWire(maskType, 0))
			for _, sf := range f.Mask.Fields {
				if sf.Doc != "" {
					writeDocComment(b, "  ", sf.Doc)
				}
				fmt.Fprintf(b, "  %s: %s;\n", toTSFieldName(sf.Name), g.tsTypeForField(sf))
			}
			continue
		}
		if f.Doc != "" {
			writeDocComment(b, "  ", f.Doc)
		}
		fmt.Fprintf(b, "  %s: %s;\n", toTSFieldName(f.Name), g.tsTypeForField(f))
	}
	b.WriteString("}\n\n")

	// create<Message>
	fmt.Fprintf(b, "export function create%s(): %s {\n  return {\n", m.Name, m.Name)
	for _, f := range m.Fields {
		if f.Const != nil {
			continue
		}
		if f.Type == "mask" {
			maskType := f.Mask.Type
			if maskType == "" {
				maskType = "u8"
			}
			maskZero := "0"
			if maskType == "u64" {
				maskZero = "0n"
			}
			fmt.Fprintf(b, "    %sMask: %s,\n", toTSFieldName(f.Name), maskZero)
			for _, sf := range f.Mask.Fields {
				fmt.Fprintf(b, "    %s: %s,\n", toTSFieldName(sf.Name), g.tsZeroExprForField(sf))
			}
			continue
		}
		fmt.Fprintf(b, "    %s: %s,\n", toTSFieldName(f.Name), g.tsZeroExprForField(f))
	}
	b.WriteString("  };\n}\n\n")

	g.useRTType("Writer")
	g.useRTType("Reader")

	// encode<Message>
	mParam := "m"
	if nonConstCount == 0 {
		mParam = "_m"
	}
	wParam := "w"
	if len(m.Fields) == 0 {
		wParam = "_w"
	}
	fmt.Fprintf(b, "export function encode%s(%s: %s, %s: Writer): void {\n", m.Name, mParam, m.Name, wParam)
	if len(m.Fields) > 0 {
		g.emitEncodeFields(b, "  ", m, m.Fields)
	}
	b.WriteString("}\n\n")

	// decode<Message>
	rParam := "r"
	if len(m.Fields) == 0 {
		rParam = "_r"
	}
	fmt.Fprintf(b, "export function decode%s(%s: Reader, %s: %s): void {\n", m.Name, rParam, mParam, m.Name)
	if len(m.Fields) > 0 {
		g.emitDecodeFields(b, "  ", m, m.Fields)
	}
	b.WriteString("}\n\n")

	// Delta helpers
	for _, f := range m.Fields {
		if f.Type == "mask" && f.Mask.Delta {
			g.emitDeltaHelpers(b, m, f)
		}
	}
}

func (g *tsGen) emitEncodeFields(b *bytes.Buffer, indent string, m Message, fields []Field) {
	inBits := false
	flushBits := func() {
		if inBits {
			fmt.Fprintf(b, "%sw.flushBits();\n", indent)
			inBits = false
		}
	}
	for _, f := range fields {
		if g.isBitPacked(f, m.Order) {
			inBits = true
			g.emitEncodeBitField(b, indent, m.Name, f)
			continue
		}
		flushBits()
		g.emitEncodeField(b, indent, m, f)
	}
	flushBits()
}

func (g *tsGen) emitEncodeBitField(b *bytes.Buffer, indent, msgName string, f Field) {
	switch f.Type {
	case "bits":
		var expr string
		if f.Const != nil {
			expr = msgName + toExportedIdent(f.Name)
		} else {
			expr = "m." + toTSFieldName(f.Name)
		}
		if f.Bits > 32 {
			fmt.Fprintf(b, "%sw.writeBitsBig(%s, %d);\n", indent, expr, f.Bits)
		} else {
			fmt.Fprintf(b, "%sw.writeBits(%s, %d);\n", indent, expr, f.Bits)
		}
	case "qfloat":
		qf := f.QFloat
		g.useRTValue("quantizeFloat")
		fmt.Fprintf(b, "%sw.writeBits(quantizeFloat(m.%s, %s, %s, %d), %d);\n",
			indent, toTSFieldName(f.Name), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, qf.Bits)
	}
}

func (g *tsGen) emitEncodeField(b *bytes.Buffer, indent string, m Message, f Field) {
	tsName := toTSFieldName(f.Name)
	goName := toExportedIdent(f.Name)
	ord := g.effectiveOrder(f.Order, m.Order)
	var valExpr string
	if f.Const != nil {
		valExpr = m.Name + goName
	} else {
		valExpr = "m." + tsName
	}

	switch f.Type {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitWriteInt(b, indent, f.Type, ord, f.Bits, valExpr)
	case "bool":
		fmt.Fprintf(b, "%sw.writeBool(%s);\n", indent, valExpr)
	case "f32":
		fmt.Fprintf(b, "%sw.writeF32(%s, %s);\n", indent, valExpr, tsLEBool(ord))
	case "qfloat":
		qf := f.QFloat
		g.useRTValue("quantizeFloat")
		qExpr := fmt.Sprintf("quantizeFloat(%s, %s, %s, %d)", valExpr, formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits)
		switch qf.Bits {
		case 8:
			fmt.Fprintf(b, "%sw.writeU8(%s);\n", indent, qExpr)
		case 16:
			fmt.Fprintf(b, "%sw.writeU16(%s, %s);\n", indent, qExpr, tsLEBool(ord))
		case 32:
			fmt.Fprintf(b, "%sw.writeU32(%s, %s);\n", indent, qExpr, tsLEBool(ord))
		}
	case "fixed":
		fx := f.Fixed
		fxOrd := g.effectiveOrder(fx.Order, f.Order, m.Order)
		var qExpr string
		if isSignedWireInt(fx.Type) {
			g.useRTValue("quantizeFixed")
			minLit, maxLit := tsSignedBoundsLit(fx.Type)
			qExpr = fmt.Sprintf("quantizeFixed(%s, %dn, %s, %s)", valExpr, fx.Scale, minLit, maxLit)
		} else {
			g.useRTValue("quantizeFixedUint")
			maxLit := tsUnsignedMaxLit(fx.Type)
			qExpr = fmt.Sprintf("quantizeFixedUint(%s, %dn, %s)", valExpr, fx.Scale, maxLit)
		}
		if isTSBigIntWireType(fx.Type, 0) {
			g.emitWriteInt(b, indent, fx.Type, fxOrd, 0, qExpr)
		} else {
			g.emitWriteInt(b, indent, fx.Type, fxOrd, 0, fmt.Sprintf("Number(%s)", qExpr))
		}
	case "bytes":
		lenKind := f.Length
		if lenKind == "" {
			lenKind = "uvarint"
		}
		if lenKind != "rest" {
			g.emitWriteLen(b, indent, lenKind, ord, valExpr+".byteLength")
		}
		fmt.Fprintf(b, "%sw.writeBytes(%s);\n", indent, valExpr)
	case "string":
		lenKind := f.Length
		if lenKind == "" {
			lenKind = "uvarint"
		}
		g.useRTValue("utf8ByteLength")
		fmt.Fprintf(b, "%s{\n%s  const blen = utf8ByteLength(%s);\n", indent, indent, valExpr)
		if lenKind != "rest" {
			g.emitWriteLen(b, indent+"  ", lenKind, ord, "blen")
		}
		fmt.Fprintf(b, "%s  w.writeStringRaw(%s, blen);\n%s}\n", indent, valExpr, indent)
	case "array":
		a := f.Array
		arrOrd := g.effectiveOrder(a.Order, f.Order, m.Order)
		elemOrd := g.effectiveOrder(a.OfOrder, a.Order, f.Order, m.Order)
		if a.Count > 0 && a.Of == "u8" {
			fmt.Fprintf(b, "%sw.writeFixedBytes(%s, %d);\n", indent, valExpr, a.Count)
			return
		}
		if a.Count > 0 {
			zeroExpr := g.tsZeroExprForElem(a.Of, a.OfBits)
			fmt.Fprintf(b, "%sfor (let i = 0; i < %d; i++) {\n", indent, a.Count)
			elemExpr := fmt.Sprintf("(%s[i] ?? %s)", valExpr, zeroExpr)
			g.emitEncodeArrayElem(b, indent+"  ", a.Of, elemOrd, a.OfBits, elemExpr)
			fmt.Fprintf(b, "%s}\n", indent)
		} else {
			lenKind := a.Length
			if lenKind == "" {
				lenKind = "uvarint"
			}
			g.emitWriteLen(b, indent, lenKind, arrOrd, valExpr+".length")
			fmt.Fprintf(b, "%sfor (let i = 0; i < %s.length; i++) {\n", indent, valExpr)
			elemExpr := fmt.Sprintf("%s[i]!", valExpr)
			g.emitEncodeArrayElem(b, indent+"  ", a.Of, elemOrd, a.OfBits, elemExpr)
			fmt.Fprintf(b, "%s}\n", indent)
		}
	case "mask":
		ms := f.Mask
		maskType := ms.Type
		if maskType == "" {
			maskType = "u8"
		}
		maskOrd := g.effectiveOrder(ms.Order, f.Order, m.Order)
		maskField := "m." + tsName + "Mask"
		isBig := maskType == "u64"
		g.emitWriteInt(b, indent, maskType, maskOrd, 0, maskField)
		zeroLit := "0"
		if isBig {
			zeroLit = "0n"
		}
		for _, sf := range ms.Fields {
			bitConst := fmt.Sprintf("%sField%s", m.Name, toExportedIdent(sf.Name))
			fmt.Fprintf(b, "%sif ((%s & %s) !== %s) {\n", indent, maskField, bitConst, zeroLit)
			if g.isBitPacked(sf, m.Order) {
				g.emitEncodeBitField(b, indent+"  ", m.Name, sf)
				fmt.Fprintf(b, "%s  w.flushBits();\n", indent)
			} else {
				g.emitEncodeField(b, indent+"  ", m, sf)
			}
			fmt.Fprintf(b, "%s}\n", indent)
		}
	default:
		if _, ok := g.env.enums[f.Type]; ok {
			g.useExtValue(f.Type, "encode"+f.Type)
			fmt.Fprintf(b, "%sencode%s(%s, w);\n", indent, f.Type, valExpr)
		} else {
			g.useExtValue(f.Type, "encode"+f.Type)
			fmt.Fprintf(b, "%sencode%s(%s, w);\n", indent, f.Type, valExpr)
		}
	}
}

func (g *tsGen) emitEncodeArrayElem(b *bytes.Buffer, indent, elemType string, ord ByteOrder, elemBits int, elemExpr string) {
	switch elemType {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitWriteInt(b, indent, elemType, ord, elemBits, elemExpr)
	case "bool":
		fmt.Fprintf(b, "%sw.writeBool(%s);\n", indent, elemExpr)
	case "f32":
		fmt.Fprintf(b, "%sw.writeF32(%s, %s);\n", indent, elemExpr, tsLEBool(ord))
	default:
		g.useExtValue(elemType, "encode"+elemType)
		fmt.Fprintf(b, "%sencode%s(%s, w);\n", indent, elemType, elemExpr)
	}
}

func (g *tsGen) emitWriteInt(b *bytes.Buffer, indent, wireType string, ord ByteOrder, bits int, expr string) {
	switch wireType {
	case "u8":
		fmt.Fprintf(b, "%sw.writeU8(%s);\n", indent, expr)
	case "i8":
		fmt.Fprintf(b, "%sw.writeI8(%s);\n", indent, expr)
	case "u16":
		fmt.Fprintf(b, "%sw.writeU16(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "i16":
		fmt.Fprintf(b, "%sw.writeI16(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "u32":
		fmt.Fprintf(b, "%sw.writeU32(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "i32":
		fmt.Fprintf(b, "%sw.writeI32(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "u64":
		fmt.Fprintf(b, "%sw.writeU64(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "i64":
		fmt.Fprintf(b, "%sw.writeI64(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "uvarint":
		if isTSBigIntWireType(wireType, bits) {
			fmt.Fprintf(b, "%sw.writeUvarintBig(%s);\n", indent, expr)
		} else {
			fmt.Fprintf(b, "%sw.writeUvarint(%s);\n", indent, expr)
		}
	case "svarint":
		if isTSBigIntWireType(wireType, bits) {
			fmt.Fprintf(b, "%sw.writeSvarintBig(%s);\n", indent, expr)
		} else {
			fmt.Fprintf(b, "%sw.writeSvarint(%s);\n", indent, expr)
		}
	}
}

func (g *tsGen) emitWriteLen(b *bytes.Buffer, indent, lenKind string, ord ByteOrder, expr string) {
	switch lenKind {
	case "u8":
		fmt.Fprintf(b, "%sw.writeU8(%s);\n", indent, expr)
	case "u16":
		fmt.Fprintf(b, "%sw.writeU16(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "u32":
		fmt.Fprintf(b, "%sw.writeU32(%s, %s);\n", indent, expr, tsLEBool(ord))
	case "uvarint":
		fmt.Fprintf(b, "%sw.writeUvarint(%s);\n", indent, expr)
	}
}

func (g *tsGen) readIntExpr(wireType string, ord ByteOrder, bits int) string {
	switch wireType {
	case "u8":
		return "r.readU8()"
	case "i8":
		return "r.readI8()"
	case "u16":
		return fmt.Sprintf("r.readU16(%s)", tsLEBool(ord))
	case "i16":
		return fmt.Sprintf("r.readI16(%s)", tsLEBool(ord))
	case "u32":
		return fmt.Sprintf("r.readU32(%s)", tsLEBool(ord))
	case "i32":
		return fmt.Sprintf("r.readI32(%s)", tsLEBool(ord))
	case "u64":
		return fmt.Sprintf("r.readU64(%s)", tsLEBool(ord))
	case "i64":
		return fmt.Sprintf("r.readI64(%s)", tsLEBool(ord))
	case "uvarint":
		if isTSBigIntWireType(wireType, bits) {
			return "r.readUvarintBig()"
		}
		return fmt.Sprintf("r.readUvarint(%d)", bits)
	case "svarint":
		if isTSBigIntWireType(wireType, bits) {
			return "r.readSvarintBig()"
		}
		return fmt.Sprintf("r.readSvarint(%d)", bits)
	default:
		return "0"
	}
}

func (g *tsGen) emitDecodeFields(b *bytes.Buffer, indent string, m Message, fields []Field) {
	inBits := false
	alignBits := func() {
		if inBits {
			fmt.Fprintf(b, "%sr.alignBits();\n", indent)
			inBits = false
		}
	}
	for _, f := range fields {
		if g.isBitPacked(f, m.Order) {
			inBits = true
			g.emitDecodeBitField(b, indent, m.Name, f)
			continue
		}
		alignBits()
		g.emitDecodeField(b, indent, m, f)
	}
	alignBits()
}

func (g *tsGen) emitDecodeBitField(b *bytes.Buffer, indent, msgName string, f Field) {
	tsName := toTSFieldName(f.Name)
	goName := toExportedIdent(f.Name)
	switch f.Type {
	case "bits":
		readCall := fmt.Sprintf("r.readBits(%d)", f.Bits)
		if f.Bits > 32 {
			readCall = fmt.Sprintf("r.readBitsBig(%d)", f.Bits)
		}
		if f.Const != nil {
			g.useRTValue("WireError")
			fmt.Fprintf(b, "%sif (%s !== %s%s) {\n%s  throw new WireError(\"invalid_const\", \"wire: unexpected constant field value\");\n%s}\n",
				indent, readCall, msgName, goName, indent, indent)
		} else {
			fmt.Fprintf(b, "%sm.%s = %s;\n", indent, tsName, readCall)
		}
	case "qfloat":
		qf := f.QFloat
		g.useRTValue("dequantizeFloat")
		fmt.Fprintf(b, "%sm.%s = dequantizeFloat(r.readBits(%d), %s, %s, %d);\n",
			indent, tsName, qf.Bits, formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits)
	}
}

func (g *tsGen) emitDecodeField(b *bytes.Buffer, indent string, m Message, f Field) {
	tsName := toTSFieldName(f.Name)
	goName := toExportedIdent(f.Name)
	ord := g.effectiveOrder(f.Order, m.Order)
	target := "m." + tsName

	if f.Const != nil {
		g.useRTValue("WireError")
		constName := m.Name + goName
		if _, isEnum := g.env.enums[f.Type]; isEnum {
			g.useExtValue(f.Type, "decode"+f.Type)
			fmt.Fprintf(b, "%sif (decode%s(r) !== %s) {\n%s  throw new WireError(\"invalid_const\", \"wire: unexpected constant field value\");\n%s}\n",
				indent, f.Type, constName, indent, indent)
			return
		}
		fmt.Fprintf(b, "%sif (%s !== %s) {\n%s  throw new WireError(\"invalid_const\", \"wire: unexpected constant field value\");\n%s}\n",
			indent, g.readIntExpr(f.Type, ord, f.Bits), constName, indent, indent)
		return
	}

	switch f.Type {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		fmt.Fprintf(b, "%s%s = %s;\n", indent, target, g.readIntExpr(f.Type, ord, f.Bits))
	case "bool":
		fmt.Fprintf(b, "%s%s = r.readBool();\n", indent, target)
	case "f32":
		fmt.Fprintf(b, "%s%s = r.readF32(%s);\n", indent, target, tsLEBool(ord))
	case "qfloat":
		qf := f.QFloat
		g.useRTValue("dequantizeFloat")
		var readQ string
		switch qf.Bits {
		case 8:
			readQ = "r.readU8()"
		case 16:
			readQ = fmt.Sprintf("r.readU16(%s)", tsLEBool(ord))
		case 32:
			readQ = fmt.Sprintf("r.readU32(%s)", tsLEBool(ord))
		}
		fmt.Fprintf(b, "%s%s = dequantizeFloat(%s, %s, %s, %d);\n",
			indent, target, readQ, formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits)
	case "fixed":
		fx := f.Fixed
		fxOrd := g.effectiveOrder(fx.Order, f.Order, m.Order)
		rawExpr := g.readIntExpr(fx.Type, fxOrd, 0)
		if !isTSBigIntWireType(fx.Type, 0) {
			rawExpr = fmt.Sprintf("BigInt(%s)", rawExpr)
		}
		if isSignedWireInt(fx.Type) {
			g.useRTValue("dequantizeFixed")
			fmt.Fprintf(b, "%s%s = dequantizeFixed(%s, %dn);\n", indent, target, rawExpr, fx.Scale)
		} else {
			g.useRTValue("dequantizeFixedUint")
			fmt.Fprintf(b, "%s%s = dequantizeFixedUint(%s, %dn);\n", indent, target, rawExpr, fx.Scale)
		}
	case "bytes", "string":
		lenKind := f.Length
		if lenKind == "" {
			lenKind = "uvarint"
		}
		fmt.Fprintf(b, "%s{\n", indent)
		if lenKind == "rest" {
			fmt.Fprintf(b, "%s  const blen = r.remaining();\n", indent)
			if f.MaxLength > 0 {
				g.useRTValue("WireError")
				fmt.Fprintf(b, "%s  if (blen > %d) {\n%s    throw new WireError(\"limit_exceeded\", \"wire: length limit exceeded\");\n%s  }\n", indent, f.MaxLength, indent, indent)
			}
		} else {
			g.emitDecodeLenCheck(b, indent+"  ", lenKind, ord, f.MaxLength, 1, "blen")
		}
		if f.Type == "bytes" {
			fmt.Fprintf(b, "%s  %s = r.readBytes(blen);\n%s}\n", indent, target, indent)
		} else {
			fmt.Fprintf(b, "%s  %s = r.readString(blen);\n%s}\n", indent, target, indent)
		}
	case "array":
		a := f.Array
		arrOrd := g.effectiveOrder(a.Order, f.Order, m.Order)
		elemOrd := g.effectiveOrder(a.OfOrder, a.Order, f.Order, m.Order)
		if a.Count > 0 && a.Of == "u8" {
			fmt.Fprintf(b, "%sif (%s.byteLength !== %d) {\n%s  %s = new Uint8Array(%d);\n%s}\n%sr.readBytesInto(%s);\n",
				indent, target, a.Count, indent, target, a.Count, indent, indent, target)
			return
		}
		if a.Count > 0 {
			fmt.Fprintf(b, "%sfor (let i = 0; i < %d; i++) {\n", indent, a.Count)
			g.emitDecodeArrayElem(b, indent+"  ", a.Of, elemOrd, a.OfBits, target, "i")
			fmt.Fprintf(b, "%s}\n%s%s.length = %d;\n", indent, indent, target, a.Count)
		} else {
			lenKind := a.Length
			if lenKind == "" {
				lenKind = "uvarint"
			}
			minElemSize := g.minTypeWireSize(a.Of)
			fmt.Fprintf(b, "%s{\n", indent)
			g.emitDecodeLenCheck(b, indent+"  ", lenKind, arrOrd, a.MaxLength, minElemSize, "count")
			if _, isMsg := g.env.messages[a.Of]; isMsg {
				g.useExtValue(a.Of, "create"+a.Of)
				fmt.Fprintf(b, "%s  for (let i = 0; i < count; i++) {\n", indent)
				fmt.Fprintf(b, "%s    let elem = %s[i];\n%s    if (elem === undefined) {\n%s      elem = create%s();\n%s      %s[i] = elem;\n%s    }\n",
					indent, target, indent, indent, a.Of, indent, target, indent)
				g.useExtValue(a.Of, "decode"+a.Of)
				fmt.Fprintf(b, "%s    decode%s(r, elem);\n%s  }\n%s  %s.length = count;\n%s}\n",
					indent, a.Of, indent, indent, target, indent)
			} else {
				fmt.Fprintf(b, "%s  %s.length = count;\n%s  for (let i = 0; i < count; i++) {\n", indent, target, indent)
				g.emitDecodeArrayElem(b, indent+"    ", a.Of, elemOrd, a.OfBits, target, "i")
				fmt.Fprintf(b, "%s  }\n%s}\n", indent, indent)
			}
		}
	case "mask":
		ms := f.Mask
		maskType := ms.Type
		if maskType == "" {
			maskType = "u8"
		}
		maskOrd := g.effectiveOrder(ms.Order, f.Order, m.Order)
		maskField := "m." + tsName + "Mask"
		maskBits, _ := maskTypeBits(maskType)
		isBig := maskType == "u64"
		zeroLit := "0"
		if isBig {
			zeroLit = "0n"
		}
		fmt.Fprintf(b, "%s%s = %s;\n", indent, maskField, g.readIntExpr(maskType, maskOrd, 0))
		if len(ms.Fields) < maskBits {
			g.useRTValue("WireError")
			if isBig {
				fmt.Fprintf(b, "%sif ((%s & ~%sMaskValid) !== 0n) {\n%s  throw new WireError(\"invalid_mask\", \"wire: unknown presence mask bit\");\n%s}\n",
					indent, maskField, m.Name, indent, indent)
			} else {
				fmt.Fprintf(b, "%sif (((%s & ~%sMaskValid) >>> 0) !== 0) {\n%s  throw new WireError(\"invalid_mask\", \"wire: unknown presence mask bit\");\n%s}\n",
					indent, maskField, m.Name, indent, indent)
			}
		}
		for _, sf := range ms.Fields {
			sfTSName := toTSFieldName(sf.Name)
			bitConst := fmt.Sprintf("%sField%s", m.Name, toExportedIdent(sf.Name))
			fmt.Fprintf(b, "%sif ((%s & %s) !== %s) {\n", indent, maskField, bitConst, zeroLit)
			if g.isBitPacked(sf, m.Order) {
				g.emitDecodeBitField(b, indent+"  ", m.Name, sf)
				fmt.Fprintf(b, "%s  r.alignBits();\n", indent)
			} else {
				g.emitDecodeField(b, indent+"  ", m, sf)
			}
			fmt.Fprintf(b, "%s} else {\n", indent)
			g.emitClearField(b, indent+"  ", sf, "m."+sfTSName)
			fmt.Fprintf(b, "%s}\n", indent)
		}
	default:
		if _, ok := g.env.enums[f.Type]; ok {
			g.useExtValue(f.Type, "decode"+f.Type)
			fmt.Fprintf(b, "%s%s = decode%s(r);\n", indent, target, f.Type)
		} else {
			g.useExtValue(f.Type, "decode"+f.Type)
			fmt.Fprintf(b, "%sdecode%s(r, %s);\n", indent, f.Type, target)
		}
	}
}

func (g *tsGen) emitDecodeLenCheck(b *bytes.Buffer, indent, lenKind string, ord ByteOrder, maxLength, minElemSize int, outVar string) {
	g.useRTValue("WireError")
	if lenKind == "uvarint" {
		fmt.Fprintf(b, "%sconst rawLen = r.readUvarintBig();\n", indent)
		if maxLength > 0 {
			fmt.Fprintf(b, "%sif (rawLen > %dn) {\n%s  throw new WireError(\"limit_exceeded\", \"wire: length limit exceeded\");\n%s}\n", indent, maxLength, indent, indent)
		}
		if minElemSize > 1 {
			fmt.Fprintf(b, "%sif (rawLen > BigInt(Math.floor(r.remaining() / %d))) {\n%s  throw new WireError(\"short_buffer\", \"wire: short buffer\");\n%s}\n", indent, minElemSize, indent, indent)
		} else {
			fmt.Fprintf(b, "%sif (rawLen > BigInt(r.remaining())) {\n%s  throw new WireError(\"short_buffer\", \"wire: short buffer\");\n%s}\n", indent, indent, indent)
		}
		fmt.Fprintf(b, "%sconst %s = Number(rawLen);\n", indent, outVar)
		return
	}
	fmt.Fprintf(b, "%sconst %s = %s;\n", indent, outVar, g.readIntExpr(lenKind, ord, 0))
	if maxLength > 0 {
		fmt.Fprintf(b, "%sif (%s > %d) {\n%s  throw new WireError(\"limit_exceeded\", \"wire: length limit exceeded\");\n%s}\n", indent, outVar, maxLength, indent, indent)
	}
	if minElemSize > 1 {
		fmt.Fprintf(b, "%sif (%s > Math.floor(r.remaining() / %d)) {\n%s  throw new WireError(\"short_buffer\", \"wire: short buffer\");\n%s}\n", indent, outVar, minElemSize, indent, indent)
	} else {
		fmt.Fprintf(b, "%sif (%s > r.remaining()) {\n%s  throw new WireError(\"short_buffer\", \"wire: short buffer\");\n%s}\n", indent, outVar, indent, indent)
	}
}

func (g *tsGen) emitDecodeArrayElem(b *bytes.Buffer, indent, elemType string, ord ByteOrder, elemBits int, arrTarget, idx string) {
	switch elemType {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		fmt.Fprintf(b, "%s%s[%s] = %s;\n", indent, arrTarget, idx, g.readIntExpr(elemType, ord, elemBits))
	case "bool":
		fmt.Fprintf(b, "%s%s[%s] = r.readBool();\n", indent, arrTarget, idx)
	case "f32":
		fmt.Fprintf(b, "%s%s[%s] = r.readF32(%s);\n", indent, arrTarget, idx, tsLEBool(ord))
	default:
		if _, ok := g.env.enums[elemType]; ok {
			g.useExtValue(elemType, "decode"+elemType)
			fmt.Fprintf(b, "%s%s[%s] = decode%s(r);\n", indent, arrTarget, idx, elemType)
		} else {
			g.useExtValue(elemType, "create"+elemType)
			g.useExtValue(elemType, "decode"+elemType)
			fmt.Fprintf(b, "%slet elem = %s[%s];\n%sif (elem === undefined) {\n%s  elem = create%s();\n%s  %s[%s] = elem;\n%s}\n%sdecode%s(r, elem);\n",
				indent, arrTarget, idx, indent, indent, elemType, indent, arrTarget, idx, indent, indent, elemType)
		}
	}
}

func (g *tsGen) emitClearField(b *bytes.Buffer, indent string, f Field, target string) {
	switch f.Type {
	case "bytes":
		g.useRTValue("EMPTY_BYTES")
		fmt.Fprintf(b, "%s%s = EMPTY_BYTES;\n", indent, target)
	case "array":
		if f.Array.Count == 0 {
			fmt.Fprintf(b, "%s%s.length = 0;\n", indent, target)
		} else if f.Array.Of == "u8" {
			fmt.Fprintf(b, "%sif (%s.byteLength !== %d) {\n%s  %s = new Uint8Array(%d);\n%s} else {\n%s  %s.fill(0);\n%s}\n",
				indent, target, f.Array.Count, indent, target, f.Array.Count, indent, indent, target, indent)
		} else {
			fmt.Fprintf(b, "%s%s = %s;\n", indent, target, g.tsZeroExprForField(f))
		}
	case "string":
		fmt.Fprintf(b, "%s%s = \"\";\n", indent, target)
	case "bool":
		fmt.Fprintf(b, "%s%s = false;\n", indent, target)
	case "u8", "u16", "u32", "i8", "i16", "i32", "f32", "qfloat", "fixed":
		fmt.Fprintf(b, "%s%s = 0;\n", indent, target)
	case "u64", "i64":
		fmt.Fprintf(b, "%s%s = 0n;\n", indent, target)
	case "uvarint", "svarint":
		if isTSBigIntWireType(f.Type, f.Bits) {
			fmt.Fprintf(b, "%s%s = 0n;\n", indent, target)
		} else {
			fmt.Fprintf(b, "%s%s = 0;\n", indent, target)
		}
	case "bits":
		if f.Bits > 32 {
			fmt.Fprintf(b, "%s%s = 0n;\n", indent, target)
		} else {
			fmt.Fprintf(b, "%s%s = 0;\n", indent, target)
		}
	default:
		fmt.Fprintf(b, "%s%s = %s;\n", indent, target, g.tsZeroExprForField(f))
	}
}

func (g *tsGen) emitDeltaHelpers(b *bytes.Buffer, m Message, maskField Field) {
	ms := maskField.Mask
	maskType := ms.Type
	if maskType == "" {
		maskType = "u8"
	}
	isBig := maskType == "u64"
	maskTSType := "number"
	zeroLit := "0"
	if isBig {
		maskTSType = "bigint"
		zeroLit = "0n"
	}
	maskTSField := toTSFieldName(maskField.Name) + "Mask"

	fmt.Fprintf(b, "export function diff%s(base: %s, cur: %s): %s {\n  let mask = %s;\n", m.Name, m.Name, m.Name, maskTSType, zeroLit)
	for _, sf := range ms.Fields {
		sfName := toTSFieldName(sf.Name)
		bitConst := fmt.Sprintf("%sField%s", m.Name, toExportedIdent(sf.Name))
		g.emitDiffCheck(b, "  ", sf, "base."+sfName, "cur."+sfName, bitConst)
	}
	if isBig {
		b.WriteString("  return mask;\n}\n\n")
	} else {
		b.WriteString("  return mask >>> 0;\n}\n\n")
	}

	fmt.Fprintf(b, "export function apply%s(base: %s, delta: %s): void {\n", m.Name, m.Name, m.Name)
	for _, sf := range ms.Fields {
		sfName := toTSFieldName(sf.Name)
		bitConst := fmt.Sprintf("%sField%s", m.Name, toExportedIdent(sf.Name))
		fmt.Fprintf(b, "  if ((delta.%s & %s) !== %s) {\n", maskTSField, bitConst, zeroLit)
		g.emitApplyCopy(b, "    ", sf, "base."+sfName, "delta."+sfName)
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\n")
}

func (g *tsGen) emitDiffCheck(b *bytes.Buffer, indent string, sf Field, baseExpr, curExpr, bitConst string) {
	switch sf.Type {
	case "f32", "qfloat":
		g.useRTValue("float32Bits")
		fmt.Fprintf(b, "%sif (float32Bits(%s) !== float32Bits(%s)) {\n%s  mask |= %s;\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "fixed":
		g.useRTValue("float64Bits")
		fmt.Fprintf(b, "%sif (float64Bits(%s) !== float64Bits(%s)) {\n%s  mask |= %s;\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "bytes":
		g.useRTValue("bytesEqual")
		fmt.Fprintf(b, "%sif (!bytesEqual(%s, %s)) {\n%s  mask |= %s;\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "array":
		if sf.Array.Count > 0 && sf.Array.Of == "u8" {
			g.useRTValue("bytesEqual")
			fmt.Fprintf(b, "%sif (!bytesEqual(%s, %s)) {\n%s  mask |= %s;\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
			return
		}
		fmt.Fprintf(b, "%s{\n%s  let diff = %s.length !== %s.length;\n%s  for (let i = 0; !diff && i < %s.length; i++) {\n", indent, indent, curExpr, baseExpr, indent, curExpr)
		if sf.Array.Of == "f32" {
			g.useRTValue("float32Bits")
			fmt.Fprintf(b, "%s    diff = float32Bits(%s[i]!) !== float32Bits(%s[i]!);\n", indent, curExpr, baseExpr)
		} else {
			fmt.Fprintf(b, "%s    diff = %s[i] !== %s[i];\n", indent, curExpr, baseExpr)
		}
		fmt.Fprintf(b, "%s  }\n%s  if (diff) {\n%s    mask |= %s;\n%s  }\n%s}\n", indent, indent, indent, bitConst, indent, indent)
	default:
		fmt.Fprintf(b, "%sif (%s !== %s) {\n%s  mask |= %s;\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	}
}

func (g *tsGen) emitApplyCopy(b *bytes.Buffer, indent string, sf Field, dstExpr, srcExpr string) {
	switch sf.Type {
	case "bytes":
		g.useRTValue("EMPTY_BYTES")
		fmt.Fprintf(b, "%s%s = %s.byteLength === 0 ? EMPTY_BYTES : %s.slice();\n", indent, dstExpr, srcExpr, srcExpr)
	case "array":
		if sf.Array.Count > 0 && sf.Array.Of == "u8" {
			fmt.Fprintf(b, "%sif (%s.byteLength !== %d) {\n%s  %s = new Uint8Array(%d);\n%s}\n%s%s.set(%s.subarray(0, %d));\n",
				indent, dstExpr, sf.Array.Count, indent, dstExpr, sf.Array.Count, indent, indent, dstExpr, srcExpr, sf.Array.Count)
		} else {
			fmt.Fprintf(b, "%s%s = %s.slice();\n", indent, dstExpr, srcExpr)
		}
	default:
		fmt.Fprintf(b, "%s%s = %s;\n", indent, dstExpr, srcExpr)
	}
}

func (g *tsGen) emitUnion(b *bytes.Buffer, u Union) {
	d := u.Discriminator
	isBig := d.Type == "uvarint"
	tagTSType := "number"
	zeroTag := "0"
	if isBig {
		tagTSType = "bigint"
		zeroTag = "0n"
	}

	if d.Type == "nibble" {
		highGoName := toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "export const %s%s = %d;\n", u.Name, highGoName, d.HighValue)
	}
	for _, c := range u.Cases {
		if c.Doc != "" {
			writeDocComment(b, "", c.Doc)
		}
		caseGoName := unionCaseGoName(c)
		fmt.Fprintf(b, "export const %sTag%s = %s;\n", u.Name, caseGoName, tsIntLiteral(c.Tag, isBig))
	}
	b.WriteByte('\n')

	if u.Doc != "" {
		writeDocComment(b, "", u.Doc)
	}
	fmt.Fprintf(b, "export interface %s {\n", u.Name)
	fmt.Fprintf(b, "  tag: %s;\n", tagTSType)
	if d.Type == "nibble" {
		fmt.Fprintf(b, "  %s: number;\n", toTSFieldName(nibbleHighName(d)))
	}
	for _, c := range u.Cases {
		g.useExtType(c.Message)
		fmt.Fprintf(b, "  %s: %s;\n", unionCaseTSName(c), c.Message)
	}
	b.WriteString("}\n\n")

	// create<Union>
	fmt.Fprintf(b, "export function create%s(): %s {\n  return {\n", u.Name, u.Name)
	fmt.Fprintf(b, "    tag: %s,\n", zeroTag)
	if d.Type == "nibble" {
		fmt.Fprintf(b, "    %s: %s%s,\n", toTSFieldName(nibbleHighName(d)), u.Name, toExportedIdent(nibbleHighName(d)))
	}
	for _, c := range u.Cases {
		g.useExtValue(c.Message, "create"+c.Message)
		fmt.Fprintf(b, "    %s: create%s(),\n", unionCaseTSName(c), c.Message)
	}
	b.WriteString("  };\n}\n\n")

	g.useRTType("Writer")
	g.useRTType("Reader")
	g.useRTValue("WireError")

	ord := g.effectiveOrder(d.Order)

	// encode<Union>
	fmt.Fprintf(b, "export function encode%s(m: %s, w: Writer): void {\n", u.Name, u.Name)
	if d.Type == "nibble" {
		hb := nibbleHighBits(d)
		lb := 8 - hb
		lowMask := (1 << lb) - 1
		highField := "m." + toTSFieldName(nibbleHighName(d))
		highConst := u.Name + toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "  let high = %s;\n", highField)
		if d.HighValue != 0 {
			fmt.Fprintf(b, "  if (high === 0) {\n    high = %s;\n  }\n", highConst)
		}
		fmt.Fprintf(b, "  w.writeU8(((high << %d) | (m.tag & 0x%x)) & 0xff);\n", lb, lowMask)
	} else {
		g.emitWriteInt(b, "  ", d.Type, ord, 0, "m.tag")
	}
	b.WriteString("  switch (m.tag) {\n")
	for _, c := range u.Cases {
		caseGoName := unionCaseGoName(c)
		caseTSName := unionCaseTSName(c)
		g.useExtValue(c.Message, "encode"+c.Message)
		fmt.Fprintf(b, "    case %sTag%s:\n      encode%s(m.%s, w);\n      break;\n", u.Name, caseGoName, c.Message, caseTSName)
	}
	b.WriteString("  }\n}\n\n")

	// decode<Union>
	fmt.Fprintf(b, "export function decode%s(r: Reader, m: %s): void {\n", u.Name, u.Name)
	if d.Type == "nibble" {
		hb := nibbleHighBits(d)
		lb := 8 - hb
		lowMask := (1 << lb) - 1
		highField := "m." + toTSFieldName(nibbleHighName(d))
		highConst := u.Name + toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "  const head = r.readU8();\n  const high = head >>> %d;\n  const tag = head & 0x%x;\n  %s = high;\n  m.tag = tag;\n", lb, lowMask, highField)
		b.WriteString("  switch (tag) {\n")
		for _, c := range u.Cases {
			fmt.Fprintf(b, "    case %sTag%s:\n", u.Name, unionCaseGoName(c))
		}
		b.WriteString("      break;\n    default:\n      throw new WireError(\"invalid_tag\", \"wire: unknown message tag\");\n  }\n")
		fmt.Fprintf(b, "  if (high !== %s) {\n    throw new WireError(\"invalid_version\", \"wire: unexpected protocol version\");\n  }\n", highConst)
	} else {
		fmt.Fprintf(b, "  const tag = %s;\n  m.tag = tag;\n", g.readIntExpr(d.Type, ord, 0))
	}
	b.WriteString("  switch (tag) {\n")
	for _, c := range u.Cases {
		caseGoName := unionCaseGoName(c)
		caseTSName := unionCaseTSName(c)
		g.useExtValue(c.Message, "decode"+c.Message)
		fmt.Fprintf(b, "    case %sTag%s:\n      decode%s(r, m.%s);\n      break;\n", u.Name, caseGoName, c.Message, caseTSName)
	}
	b.WriteString("    default:\n      throw new WireError(\"invalid_tag\", \"wire: unknown message tag\");\n  }\n}\n\n")
}

func (g *tsGen) minTypeWireSize(t string) int {
	switch t {
	case "u8", "i8", "bool", "uvarint", "svarint":
		return 1
	case "u16", "i16":
		return 2
	case "u32", "i32", "f32":
		return 4
	case "u64", "i64":
		return 8
	}
	if en, ok := g.env.enums[t]; ok {
		return g.minTypeWireSize(en.Type)
	}
	if sz, ok := g.minWireSizes[t]; ok {
		return sz
	}
	m, ok := g.env.messages[t]
	if !ok {
		return 1
	}
	g.minWireSizes[t] = 0
	total := 0
	bitRun := 0
	for _, f := range m.Fields {
		if g.isBitPacked(f, m.Order) {
			if f.Type == "bits" {
				bitRun += f.Bits
			} else {
				bitRun += f.QFloat.Bits
			}
			continue
		}
		if bitRun > 0 {
			total += (bitRun + 7) / 8
			bitRun = 0
		}
		switch f.Type {
		case "bytes", "string":
			switch f.Length {
			case "rest":
			case "", "uvarint", "u8":
				total++
			case "u16":
				total += 2
			case "u32":
				total += 4
			}
		case "array":
			if f.Array.Count > 0 {
				total += f.Array.Count * g.minTypeWireSize(f.Array.Of)
			} else {
				switch f.Array.Length {
				case "", "uvarint", "u8":
					total++
				case "u16":
					total += 2
				case "u32":
					total += 4
				}
			}
		case "mask":
			mt := f.Mask.Type
			if mt == "" {
				mt = "u8"
			}
			total += g.minTypeWireSize(mt)
		case "fixed":
			total += g.minTypeWireSize(f.Fixed.Type)
		case "qfloat":
			total += (f.QFloat.Bits + 7) / 8
		default:
			total += g.minTypeWireSize(f.Type)
		}
	}
	if bitRun > 0 {
		total += (bitRun + 7) / 8
	}
	g.minWireSizes[t] = total
	return total
}

func unionCaseTSName(c UnionCase) string {
	if c.Name != "" {
		return toTSFieldName(c.Name)
	}
	return toTSFieldName(c.Message)
}

func tsSignedBoundsLit(t string) (string, string) {
	switch t {
	case "i8":
		return "-128n", "127n"
	case "i16":
		return "-32768n", "32767n"
	case "i32":
		return "-2147483648n", "2147483647n"
	default:
		return "-9223372036854775808n", "9223372036854775807n"
	}
}

func tsUnsignedMaxLit(t string) string {
	switch t {
	case "u8":
		return "255n"
	case "u16":
		return "65535n"
	case "u32":
		return "4294967295n"
	default:
		return "18446744073709551615n"
	}
}

// toTSFieldName converts snake_case or PascalCase schema field names to idiomatic lowerCamelCase TypeScript property names.
func toTSFieldName(s string) string {
	if s == "" {
		return ""
	}
	if !strings.ContainsRune(s, '_') {
		runes := []rune(s)
		if !unicode.IsUpper(runes[0]) {
			return s
		}
		// Lowercase leading uppercase run (e.g. "ID" -> "id", "UDPFrame" -> "udpFrame").
		i := 0
		for i < len(runes) && unicode.IsUpper(runes[i]) {
			i++
		}
		if i == len(runes) {
			return strings.ToLower(s)
		}
		if i > 1 {
			i--
		}
		for j := 0; j < i; j++ {
			runes[j] = unicode.ToLower(runes[j])
		}
		return string(runes)
	}
	parts := strings.Split(s, "_")
	var b strings.Builder
	first := true
	for _, p := range parts {
		if p == "" {
			continue
		}
		if first {
			b.WriteString(strings.ToLower(p))
			first = false
			continue
		}
		runes := []rune(p)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}
	return b.String()
}

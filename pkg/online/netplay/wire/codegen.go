package wire

import (
	"bytes"
	"fmt"
	"go/format"
	"slices"
	"strconv"
	"strings"
)

// DefaultRuntimeImport is the Go import path used by generated codecs outside pkg/online/netplay/wire.
const DefaultRuntimeImport = "github.com/nsgo-dev/game/pkg/online/netplay/wire"

// GenerateOptions configures Go codec generation in GenerateGo.
type GenerateOptions struct {
	// Package overrides schema.Package when non-empty.
	Package string
	// SourceName is the schema file name shown in the generated header comment.
	SourceName string
	// Self omits the runtime package import and references runtime helpers unqualified, for files generated inside pkg/net/wire itself.
	Self bool
	// RuntimeImport overrides DefaultRuntimeImport when Self is false.
	RuntimeImport string
	// ExtraSchemas supplies sibling schemas in the same package whose enums and messages schema references via imports.
	ExtraSchemas []*Schema
}

// GenerateGo generates deterministic, formatted, zero-allocation Go codec source for schema.
func GenerateGo(schema *Schema, opts GenerateOptions) ([]byte, error) {
	if schema == nil {
		return nil, fmt.Errorf("wire: codegen: schema is nil")
	}
	all := make([]*Schema, 0, 1+len(opts.ExtraSchemas))
	all = append(all, schema)
	all = append(all, opts.ExtraSchemas...)
	if err := ValidateAll(all); err != nil {
		return nil, err
	}

	env := newTypeEnv()
	for _, s := range all {
		for _, en := range s.Enums {
			env.enums[en.Name] = en
		}
		for _, m := range s.Messages {
			env.messages[m.Name] = m
		}
		for _, u := range s.Unions {
			env.unions[u.Name] = u
		}
	}

	pkgName := opts.Package
	if pkgName == "" {
		pkgName = schema.Package
	}
	if !isGoIdent(pkgName) {
		return nil, fmt.Errorf("wire: codegen: invalid package name %q", pkgName)
	}

	runtimeImport := opts.RuntimeImport
	if runtimeImport == "" {
		runtimeImport = DefaultRuntimeImport
	}

	g := &goGen{
		schema:        schema,
		env:           env,
		self:          opts.Self,
		runtimeImport: runtimeImport,
		imports:       make(map[string]bool),
		minWireSizes:  make(map[string]int),
	}

	var body bytes.Buffer
	for _, en := range schema.Enums {
		g.emitEnum(&body, en)
	}
	for _, m := range schema.Messages {
		g.emitMessage(&body, m)
	}
	for _, u := range schema.Unions {
		g.emitUnion(&body, u)
	}

	var out bytes.Buffer
	if opts.SourceName != "" {
		fmt.Fprintf(&out, "// Code generated by gamewire from %s; DO NOT EDIT.\n\n", opts.SourceName)
	} else {
		out.WriteString("// Code generated by gamewire; DO NOT EDIT.\n\n")
	}
	fmt.Fprintf(&out, "package %s\n\n", pkgName)

	g.emitImports(&out)
	out.Write(body.Bytes())

	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("wire: codegen: format generated Go: %w\n%s", err, out.String())
	}
	return formatted, nil
}

type goGen struct {
	schema        *Schema
	env           *typeEnv
	self          bool
	runtimeImport string
	imports       map[string]bool
	minWireSizes  map[string]int
}

func (g *goGen) useStd(pkg string) {
	g.imports[pkg] = true
}

func (g *goGen) rt(sym string) string {
	if g.self {
		return sym
	}
	g.imports[g.runtimeImport] = true
	return "wire." + sym
}

func (g *goGen) emitImports(out *bytes.Buffer) {
	if len(g.imports) == 0 {
		return
	}
	var std, ext []string
	for p := range g.imports {
		if strings.Contains(p, ".") {
			ext = append(ext, p)
		} else {
			std = append(std, p)
		}
	}
	slices.Sort(std)
	slices.Sort(ext)
	out.WriteString("import (\n")
	for _, p := range std {
		fmt.Fprintf(out, "\t%q\n", p)
	}
	if len(std) > 0 && len(ext) > 0 {
		out.WriteByte('\n')
	}
	for _, p := range ext {
		fmt.Fprintf(out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
}

func (g *goGen) effectiveOrder(orders ...ByteOrder) ByteOrder {
	for _, o := range orders {
		if o != "" {
			return o
		}
	}
	if g.schema.Order != "" {
		return g.schema.Order
	}
	return OrderBig
}

func (g *goGen) binaryOrderExpr(o ByteOrder) string {
	g.useStd("encoding/binary")
	if o == OrderLittle {
		return "binary.LittleEndian"
	}
	return "binary.BigEndian"
}

func writeDocComment(b *bytes.Buffer, indent, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(strings.TrimRight(doc, "\n"), "\n") {
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}

func goIntTypeForWire(wireType string, bits int) string {
	switch wireType {
	case "u8":
		return "uint8"
	case "u16":
		return "uint16"
	case "u32":
		return "uint32"
	case "u64":
		return "uint64"
	case "i8":
		return "int8"
	case "i16":
		return "int16"
	case "i32":
		return "int32"
	case "i64":
		return "int64"
	case "uvarint":
		switch bits {
		case 8:
			return "uint8"
		case 16:
			return "uint16"
		case 32:
			return "uint32"
		default:
			return "uint64"
		}
	case "svarint":
		switch bits {
		case 8:
			return "int8"
		case 16:
			return "int16"
		case 32:
			return "int32"
		default:
			return "int64"
		}
	case "bits":
		switch {
		case bits <= 8:
			return "uint8"
		case bits <= 16:
			return "uint16"
		case bits <= 32:
			return "uint32"
		default:
			return "uint64"
		}
	case "bool":
		return "bool"
	case "f32", "qfloat":
		return "float32"
	case "fixed":
		return "float64"
	case "bytes":
		return "[]byte"
	case "string":
		return "string"
	default:
		return wireType
	}
}

func (g *goGen) goTypeForField(f Field) string {
	switch f.Type {
	case "array":
		elemType := g.goTypeForArrayElem(f.Array)
		if f.Array.Count > 0 {
			return fmt.Sprintf("[%d]%s", f.Array.Count, elemType)
		}
		return "[]" + elemType
	default:
		return goIntTypeForWire(f.Type, f.Bits)
	}
}

func (g *goGen) goTypeForArrayElem(a *ArraySpec) string {
	return goIntTypeForWire(a.Of, a.OfBits)
}

func (g *goGen) emitEnum(b *bytes.Buffer, en Enum) {
	baseType := goIntTypeForWire(en.Type, 0)
	if en.Doc != "" {
		writeDocComment(b, "", en.Doc)
	}
	fmt.Fprintf(b, "type %s %s\n\n", en.Name, baseType)

	b.WriteString("const (\n")
	for _, v := range en.Values {
		if v.Doc != "" {
			writeDocComment(b, "\t", v.Doc)
		}
		fmt.Fprintf(b, "\t%s%s %s = %d\n", en.Name, toExportedIdent(v.Name), en.Name, v.Value)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(b, "// Valid reports whether v is a declared %s value.\n", en.Name)
	fmt.Fprintf(b, "func (v %s) Valid() bool {\n\tswitch v {\n\tcase ", en.Name)
	for i, v := range en.Values {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%s%s", en.Name, toExportedIdent(v.Name))
	}
	b.WriteString(":\n\t\treturn true\n\tdefault:\n\t\treturn false\n\t}\n}\n\n")

	ord := g.effectiveOrder(en.Order)
	fmt.Fprintf(b, "// Append%s appends v to dst in wire format.\n", en.Name)
	fmt.Fprintf(b, "func Append%s(dst []byte, v %s) []byte {\n", en.Name, en.Name)
	g.emitAppendInt(b, "\t", en.Type, ord, baseType+"(v)")
	b.WriteString("\treturn dst\n}\n\n")

	fmt.Fprintf(b, "// Decode%s decodes one %s from src into v, validating that it is a declared enum value.\n", en.Name, en.Name)
	fmt.Fprintf(b, "func Decode%s(src []byte, v *%s) (int, error) {\n\toff := 0\n\tvar raw %s\n", en.Name, en.Name, baseType)
	g.emitDecodeInt(b, "\t", en.Type, ord, 0, "raw")
	fmt.Fprintf(b, "\tval := %s(raw)\n\tif !val.Valid() {\n\t\treturn 0, %s\n\t}\n\t*v = val\n\treturn off, nil\n}\n\n", en.Name, g.rt("ErrInvalidEnum"))
}

func (g *goGen) emitMessage(b *bytes.Buffer, m Message) {
	// Emit constants for const fields and mask groups.
	var constLines bytes.Buffer
	for _, f := range m.Fields {
		if f.Const != nil {
			goType := g.goTypeForField(f)
			fmt.Fprintf(&constLines, "\t%s%s %s = %d\n", m.Name, toExportedIdent(f.Name), goType, *f.Const)
		}
		if f.Type == "mask" {
			maskType := f.Mask.Type
			if maskType == "" {
				maskType = "u8"
			}
			maskGoType := goIntTypeForWire(maskType, 0)
			var validMask uint64
			for i, sf := range f.Mask.Fields {
				validMask |= uint64(1) << i
				fmt.Fprintf(&constLines, "\t%sField%s %s = 1 << %d\n", m.Name, toExportedIdent(sf.Name), maskGoType, i)
			}
			fmt.Fprintf(&constLines, "\t%sMaskValid %s = 0x%x\n", m.Name, maskGoType, validMask)
		}
	}
	if constLines.Len() > 0 {
		b.WriteString("const (\n")
		b.Write(constLines.Bytes())
		b.WriteString(")\n\n")
	}

	if m.Doc != "" {
		writeDocComment(b, "", m.Doc)
	}
	fmt.Fprintf(b, "type %s struct {\n", m.Name)
	for _, f := range m.Fields {
		if f.Const != nil {
			continue
		}
		if f.Type == "mask" {
			maskType := f.Mask.Type
			if maskType == "" {
				maskType = "u8"
			}
			if f.Doc != "" {
				writeDocComment(b, "\t", f.Doc)
			}
			fmt.Fprintf(b, "\t%sMask %s\n", toExportedIdent(f.Name), goIntTypeForWire(maskType, 0))
			for _, sf := range f.Mask.Fields {
				if sf.Doc != "" {
					writeDocComment(b, "\t", sf.Doc)
				}
				fmt.Fprintf(b, "\t%s %s\n", toExportedIdent(sf.Name), g.goTypeForField(sf))
			}
			continue
		}
		if f.Doc != "" {
			writeDocComment(b, "\t", f.Doc)
		}
		fmt.Fprintf(b, "\t%s %s\n", toExportedIdent(f.Name), g.goTypeForField(f))
	}
	b.WriteString("}\n\n")

	// Append<Message>
	fmt.Fprintf(b, "// Append%s encodes m onto dst in wire format without allocating when dst has capacity.\n", m.Name)
	fmt.Fprintf(b, "func Append%s(dst []byte, m *%s) []byte {\n", m.Name, m.Name)
	if len(m.Fields) == 0 {
		b.WriteString("\t_ = m\n\treturn dst\n}\n\n")
	} else {
		g.emitEncodeFields(b, "\t", m, m.Fields)
		b.WriteString("\treturn dst\n}\n\n")
	}

	// Decode<Message>
	fmt.Fprintf(b, "// Decode%s decodes one %s from src into caller-owned storage m without heap allocations once slices have capacity.\n", m.Name, m.Name)
	fmt.Fprintf(b, "func Decode%s(src []byte, m *%s) (int, error) {\n", m.Name, m.Name)
	if len(m.Fields) == 0 {
		b.WriteString("\t_, _ = src, m\n\treturn 0, nil\n}\n\n")
	} else {
		b.WriteString("\toff := 0\n")
		g.emitDecodeFields(b, "\t", m, m.Fields)
		b.WriteString("\treturn off, nil\n}\n\n")
	}

	// Delta Diff and Apply helpers for mask groups with delta: true.
	for _, f := range m.Fields {
		if f.Type == "mask" && f.Mask.Delta {
			g.emitDeltaHelpers(b, m, f)
		}
	}
}

func (g *goGen) isBitPacked(f Field, msgOrder ByteOrder) bool {
	if f.Type == "bits" {
		return true
	}
	if f.Type == "qfloat" {
		ord := g.effectiveOrder(f.Order, msgOrder)
		if ord == OrderLittle && (f.QFloat.Bits == 8 || f.QFloat.Bits == 16 || f.QFloat.Bits == 32) {
			return false
		}
		return true
	}
	return false
}

func (g *goGen) emitEncodeFields(b *bytes.Buffer, indent string, m Message, fields []Field) {
	inBits := false
	bwDeclared := false
	flushBits := func() {
		if inBits {
			fmt.Fprintf(b, "%sdst = bw.Flush()\n", indent)
			inBits = false
		}
	}
	for _, f := range fields {
		if g.isBitPacked(f, m.Order) {
			if !inBits {
				if !bwDeclared {
					fmt.Fprintf(b, "%sbw := %s{Dst: dst}\n", indent, g.rt("BitWriter"))
					bwDeclared = true
				} else {
					fmt.Fprintf(b, "%sbw = %s{Dst: dst}\n", indent, g.rt("BitWriter"))
				}
				inBits = true
			}
			g.emitEncodeBitField(b, indent, m.Name, f)
			continue
		}
		flushBits()
		g.emitEncodeField(b, indent, m, f)
	}
	flushBits()
}

func (g *goGen) emitEncodeBitField(b *bytes.Buffer, indent, msgName string, f Field) {
	switch f.Type {
	case "bits":
		if f.Const != nil {
			fmt.Fprintf(b, "%sbw.WriteBits(uint64(%s%s), %d)\n", indent, msgName, toExportedIdent(f.Name), f.Bits)
		} else {
			fmt.Fprintf(b, "%sbw.WriteBits(uint64(m.%s), %d)\n", indent, toExportedIdent(f.Name), f.Bits)
		}
	case "qfloat":
		qf := f.QFloat
		fmt.Fprintf(b, "%sbw.WriteBits(uint64(%s(m.%s, %s, %s, %d)), %d)\n",
			indent, g.rt("QuantizeFloat"), toExportedIdent(f.Name), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, qf.Bits)
	}
}

func (g *goGen) emitEncodeField(b *bytes.Buffer, indent string, m Message, f Field) {
	goName := toExportedIdent(f.Name)
	ord := g.effectiveOrder(f.Order, m.Order)
	var valExpr string
	if f.Const != nil {
		valExpr = fmt.Sprintf("%s%s", m.Name, goName)
	} else {
		valExpr = "m." + goName
	}

	switch f.Type {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitAppendInt(b, indent, f.Type, ord, valExpr)
	case "bool":
		fmt.Fprintf(b, "%sif %s {\n%s\tdst = append(dst, 1)\n%s} else {\n%s\tdst = append(dst, 0)\n%s}\n", indent, valExpr, indent, indent, indent, indent)
	case "f32":
		g.useStd("math")
		fmt.Fprintf(b, "%sdst = %s.AppendUint32(dst, math.Float32bits(%s))\n", indent, g.binaryOrderExpr(ord), valExpr)
	case "qfloat":
		// Byte-aligned little-endian 8/16/32-bit qfloat.
		qf := f.QFloat
		qExpr := fmt.Sprintf("%s(%s, %s, %s, %d)", g.rt("QuantizeFloat"), valExpr, formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits)
		switch qf.Bits {
		case 8:
			fmt.Fprintf(b, "%sdst = append(dst, byte(%s))\n", indent, qExpr)
		case 16:
			fmt.Fprintf(b, "%sdst = %s.AppendUint16(dst, uint16(%s))\n", indent, g.binaryOrderExpr(ord), qExpr)
		case 32:
			fmt.Fprintf(b, "%sdst = %s.AppendUint32(dst, %s)\n", indent, g.binaryOrderExpr(ord), qExpr)
		}
	case "fixed":
		fx := f.Fixed
		fxOrd := g.effectiveOrder(fx.Order, f.Order, m.Order)
		if isSignedWireInt(fx.Type) {
			minExpr, maxExpr := g.signedBoundsExpr(fx.Type)
			qExpr := fmt.Sprintf("%s(%s, %d, %s, %s)", g.rt("QuantizeFixed"), valExpr, fx.Scale, minExpr, maxExpr)
			g.emitAppendInt(b, indent, fx.Type, fxOrd, qExpr)
		} else {
			maxExpr := g.unsignedMaxExpr(fx.Type)
			qExpr := fmt.Sprintf("%s(%s, %d, %s)", g.rt("QuantizeFixedUint"), valExpr, fx.Scale, maxExpr)
			g.emitAppendInt(b, indent, fx.Type, fxOrd, qExpr)
		}
	case "bytes", "string":
		lenKind := f.Length
		if lenKind == "" {
			lenKind = "uvarint"
		}
		if lenKind != "rest" {
			g.emitAppendInt(b, indent, lenKind, ord, fmt.Sprintf("len(%s)", valExpr))
		}
		fmt.Fprintf(b, "%sdst = append(dst, %s...)\n", indent, valExpr)
	case "array":
		a := f.Array
		arrOrd := g.effectiveOrder(a.Order, f.Order, m.Order)
		elemOrd := g.effectiveOrder(a.OfOrder, a.Order, f.Order, m.Order)
		if a.Count == 0 {
			lenKind := a.Length
			if lenKind == "" {
				lenKind = "uvarint"
			}
			g.emitAppendInt(b, indent, lenKind, arrOrd, fmt.Sprintf("len(%s)", valExpr))
		}
		fmt.Fprintf(b, "%sfor i := range %s {\n", indent, valExpr)
		elemExpr := fmt.Sprintf("%s[i]", valExpr)
		g.emitEncodeArrayElem(b, indent+"\t", a.Of, elemOrd, elemExpr)
		fmt.Fprintf(b, "%s}\n", indent)
	case "mask":
		ms := f.Mask
		maskType := ms.Type
		if maskType == "" {
			maskType = "u8"
		}
		maskOrd := g.effectiveOrder(ms.Order, f.Order, m.Order)
		maskField := "m." + goName + "Mask"
		g.emitAppendInt(b, indent, maskType, maskOrd, maskField)
		for _, sf := range ms.Fields {
			bitConst := fmt.Sprintf("%sField%s", m.Name, toExportedIdent(sf.Name))
			fmt.Fprintf(b, "%sif %s&%s != 0 {\n", indent, maskField, bitConst)
			if g.isBitPacked(sf, m.Order) {
				fmt.Fprintf(b, "%s\tbwMask := %s{Dst: dst}\n", indent, g.rt("BitWriter"))
				switch sf.Type {
				case "bits":
					fmt.Fprintf(b, "%s\tbwMask.WriteBits(uint64(m.%s), %d)\n", indent, toExportedIdent(sf.Name), sf.Bits)
				case "qfloat":
					qf := sf.QFloat
					fmt.Fprintf(b, "%s\tbwMask.WriteBits(uint64(%s(m.%s, %s, %s, %d)), %d)\n",
						indent, g.rt("QuantizeFloat"), toExportedIdent(sf.Name), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, qf.Bits)
				}
				fmt.Fprintf(b, "%s\tdst = bwMask.Flush()\n", indent)
			} else {
				g.emitEncodeField(b, indent+"\t", m, sf)
			}
			fmt.Fprintf(b, "%s}\n", indent)
		}
	default:
		if _, ok := g.env.enums[f.Type]; ok {
			fmt.Fprintf(b, "%sdst = Append%s(dst, %s)\n", indent, f.Type, valExpr)
		} else {
			fmt.Fprintf(b, "%sdst = Append%s(dst, &%s)\n", indent, f.Type, valExpr)
		}
	}
}

func (g *goGen) emitEncodeArrayElem(b *bytes.Buffer, indent, elemType string, ord ByteOrder, elemExpr string) {
	switch elemType {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitAppendInt(b, indent, elemType, ord, elemExpr)
	case "bool":
		fmt.Fprintf(b, "%sif %s {\n%s\tdst = append(dst, 1)\n%s} else {\n%s\tdst = append(dst, 0)\n%s}\n", indent, elemExpr, indent, indent, indent, indent)
	case "f32":
		g.useStd("math")
		fmt.Fprintf(b, "%sdst = %s.AppendUint32(dst, math.Float32bits(%s))\n", indent, g.binaryOrderExpr(ord), elemExpr)
	default:
		if _, ok := g.env.enums[elemType]; ok {
			fmt.Fprintf(b, "%sdst = Append%s(dst, %s)\n", indent, elemType, elemExpr)
		} else {
			fmt.Fprintf(b, "%sdst = Append%s(dst, &%s)\n", indent, elemType, elemExpr)
		}
	}
}

func (g *goGen) emitAppendInt(b *bytes.Buffer, indent, wireType string, ord ByteOrder, expr string) {
	switch wireType {
	case "u8":
		fmt.Fprintf(b, "%sdst = append(dst, byte(%s))\n", indent, expr)
	case "i8":
		fmt.Fprintf(b, "%sdst = append(dst, byte(uint8(%s)))\n", indent, expr)
	case "u16":
		fmt.Fprintf(b, "%sdst = %s.AppendUint16(dst, uint16(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "i16":
		fmt.Fprintf(b, "%sdst = %s.AppendUint16(dst, uint16(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "u32":
		fmt.Fprintf(b, "%sdst = %s.AppendUint32(dst, uint32(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "i32":
		fmt.Fprintf(b, "%sdst = %s.AppendUint32(dst, uint32(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "u64":
		fmt.Fprintf(b, "%sdst = %s.AppendUint64(dst, uint64(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "i64":
		fmt.Fprintf(b, "%sdst = %s.AppendUint64(dst, uint64(%s))\n", indent, g.binaryOrderExpr(ord), expr)
	case "uvarint":
		g.useStd("encoding/binary")
		fmt.Fprintf(b, "%sdst = binary.AppendUvarint(dst, uint64(%s))\n", indent, expr)
	case "svarint":
		g.useStd("encoding/binary")
		fmt.Fprintf(b, "%sdst = binary.AppendVarint(dst, int64(%s))\n", indent, expr)
	}
}

func (g *goGen) emitDecodeFields(b *bytes.Buffer, indent string, m Message, fields []Field) {
	inBits := false
	brDeclared := false
	alignBits := func() {
		if inBits {
			fmt.Fprintf(b, "%sif err := br.Align(); err != nil {\n%s\treturn 0, err\n%s}\n%soff = br.Off\n", indent, indent, indent, indent)
			inBits = false
		}
	}
	for _, f := range fields {
		if g.isBitPacked(f, m.Order) {
			if !inBits {
				if !brDeclared {
					fmt.Fprintf(b, "%sbr := %s{Src: src, Off: off}\n", indent, g.rt("BitReader"))
					brDeclared = true
				} else {
					fmt.Fprintf(b, "%sbr = %s{Src: src, Off: off}\n", indent, g.rt("BitReader"))
				}
				inBits = true
			}
			g.emitDecodeBitField(b, indent, m.Name, f)
			continue
		}
		alignBits()
		g.emitDecodeField(b, indent, m, f)
	}
	alignBits()
}

func (g *goGen) emitDecodeBitField(b *bytes.Buffer, indent, msgName string, f Field) {
	goName := toExportedIdent(f.Name)
	switch f.Type {
	case "bits":
		fmt.Fprintf(b, "%s{\n%s\tv, err := br.ReadBits(%d)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n", indent, indent, f.Bits, indent, indent, indent)
		if f.Const != nil {
			fmt.Fprintf(b, "%s\tif v != uint64(%s%s) {\n%s\t\treturn 0, %s\n%s\t}\n", indent, msgName, goName, indent, g.rt("ErrInvalidConst"), indent)
		} else {
			fmt.Fprintf(b, "%s\tm.%s = %s(v)\n", indent, goName, goIntTypeForWire("bits", f.Bits))
		}
		fmt.Fprintf(b, "%s}\n", indent)
	case "qfloat":
		qf := f.QFloat
		fmt.Fprintf(b, "%s{\n%s\tv, err := br.ReadBits(%d)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\tm.%s = %s(uint32(v), %s, %s, %d)\n%s}\n",
			indent, indent, qf.Bits, indent, indent, indent, indent, goName, g.rt("DequantizeFloat"), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, indent)
	}
}

func (g *goGen) emitDecodeField(b *bytes.Buffer, indent string, m Message, f Field) {
	goName := toExportedIdent(f.Name)
	ord := g.effectiveOrder(f.Order, m.Order)
	target := "m." + goName

	if f.Const != nil {
		constName := m.Name + goName
		if _, isEnum := g.env.enums[f.Type]; isEnum {
			fmt.Fprintf(b, "%s{\n%s\tvar got %s\n%s\tn, err := Decode%s(src[off:], &got)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\toff += n\n%s\tif got != %s {\n%s\t\treturn 0, %s\n%s\t}\n%s}\n",
				indent, indent, f.Type, indent, f.Type, indent, indent, indent, indent, indent, constName, indent, g.rt("ErrInvalidConst"), indent, indent)
			return
		}
		goType := g.goTypeForField(f)
		fmt.Fprintf(b, "%s{\n%s\tvar got %s\n", indent, indent, goType)
		g.emitDecodeInt(b, indent+"\t", f.Type, ord, f.Bits, "got")
		fmt.Fprintf(b, "%s\tif got != %s {\n%s\t\treturn 0, %s\n%s\t}\n%s}\n", indent, constName, indent, g.rt("ErrInvalidConst"), indent, indent)
		return
	}

	switch f.Type {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitDecodeInt(b, indent, f.Type, ord, f.Bits, target)
	case "bool":
		fmt.Fprintf(b, "%sif len(src)-off < 1 {\n%s\treturn 0, %s\n%s}\n%sswitch src[off] {\n%scase 0:\n%s\t%s = false\n%scase 1:\n%s\t%s = true\n%sdefault:\n%s\treturn 0, %s\n%s}\n%soff++\n",
			indent, indent, g.rt("ErrShortBuffer"), indent, indent, indent, indent, target, indent, indent, target, indent, indent, g.rt("ErrInvalidBool"), indent, indent)
	case "f32":
		g.useStd("math")
		fmt.Fprintf(b, "%sif len(src)-off < 4 {\n%s\treturn 0, %s\n%s}\n%s%s = math.Float32frombits(%s.Uint32(src[off : off+4]))\n%soff += 4\n",
			indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "qfloat":
		qf := f.QFloat
		fmt.Fprintf(b, "%s{\n", indent)
		switch qf.Bits {
		case 8:
			fmt.Fprintf(b, "%s\tvar q uint8\n", indent)
			g.emitDecodeInt(b, indent+"\t", "u8", ord, 0, "q")
		case 16:
			fmt.Fprintf(b, "%s\tvar q uint16\n", indent)
			g.emitDecodeInt(b, indent+"\t", "u16", ord, 0, "q")
		case 32:
			fmt.Fprintf(b, "%s\tvar q uint32\n", indent)
			g.emitDecodeInt(b, indent+"\t", "u32", ord, 0, "q")
		}
		fmt.Fprintf(b, "%s\t%s = %s(uint32(q), %s, %s, %d)\n%s}\n",
			indent, target, g.rt("DequantizeFloat"), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, indent)
	case "fixed":
		fx := f.Fixed
		fxOrd := g.effectiveOrder(fx.Order, f.Order, m.Order)
		rawType := goIntTypeForWire(fx.Type, 0)
		fmt.Fprintf(b, "%s{\n%s\tvar raw %s\n", indent, indent, rawType)
		g.emitDecodeInt(b, indent+"\t", fx.Type, fxOrd, 0, "raw")
		if isSignedWireInt(fx.Type) {
			fmt.Fprintf(b, "%s\t%s = %s(int64(raw), %d)\n", indent, target, g.rt("DequantizeFixed"), fx.Scale)
		} else {
			fmt.Fprintf(b, "%s\t%s = %s(uint64(raw), %d)\n", indent, target, g.rt("DequantizeFixedUint"), fx.Scale)
		}
		fmt.Fprintf(b, "%s}\n", indent)
	case "bytes", "string":
		lenKind := f.Length
		if lenKind == "" {
			lenKind = "uvarint"
		}
		fmt.Fprintf(b, "%s{\n", indent)
		if lenKind == "rest" {
			fmt.Fprintf(b, "%s\tblen := len(src) - off\n", indent)
			if f.MaxLength > 0 {
				fmt.Fprintf(b, "%s\tif blen > %d {\n%s\t\treturn 0, %s\n%s\t}\n", indent, f.MaxLength, indent, g.rt("ErrLimitExceeded"), indent)
			}
		} else {
			fmt.Fprintf(b, "%s\tvar rawLen uint64\n", indent)
			g.emitDecodeLen(b, indent+"\t", lenKind, ord, "rawLen")
			if f.MaxLength > 0 {
				fmt.Fprintf(b, "%s\tif rawLen > %d {\n%s\t\treturn 0, %s\n%s\t}\n", indent, f.MaxLength, indent, g.rt("ErrLimitExceeded"), indent)
			}
			fmt.Fprintf(b, "%s\tif rawLen > uint64(len(src)-off) {\n%s\t\treturn 0, %s\n%s\t}\n%s\tblen := int(rawLen)\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent)
		}
		if f.Type == "bytes" {
			fmt.Fprintf(b, "%s\tif blen == 0 {\n%s\t\t%s = %s[:0]\n%s\t} else {\n%s\t\t%s = append(%s[:0], src[off:off+blen]...)\n%s\t}\n", indent, indent, target, target, indent, indent, target, target, indent)
		} else {
			fmt.Fprintf(b, "%s\tif blen == 0 {\n%s\t\t%s = \"\"\n%s\t} else if len(%s) != blen || %s != string(src[off:off+blen]) {\n%s\t\t%s = string(src[off : off+blen])\n%s\t}\n", indent, indent, target, indent, target, target, indent, target, indent)
		}
		fmt.Fprintf(b, "%s\toff += blen\n%s}\n", indent, indent)
	case "array":
		a := f.Array
		arrOrd := g.effectiveOrder(a.Order, f.Order, m.Order)
		elemOrd := g.effectiveOrder(a.OfOrder, a.Order, f.Order, m.Order)
		elemGoType := g.goTypeForArrayElem(a)
		if a.Count > 0 {
			fmt.Fprintf(b, "%sfor i := range %s {\n", indent, target)
			g.emitDecodeArrayElem(b, indent+"\t", a.Of, elemOrd, a.OfBits, fmt.Sprintf("%s[i]", target))
			fmt.Fprintf(b, "%s}\n", indent)
		} else {
			lenKind := a.Length
			if lenKind == "" {
				lenKind = "uvarint"
			}
			minElemSize := g.minTypeWireSize(a.Of)
			fmt.Fprintf(b, "%s{\n%s\tvar rawCount uint64\n", indent, indent)
			g.emitDecodeLen(b, indent+"\t", lenKind, arrOrd, "rawCount")
			if a.MaxLength > 0 {
				fmt.Fprintf(b, "%s\tif rawCount > %d {\n%s\t\treturn 0, %s\n%s\t}\n", indent, a.MaxLength, indent, g.rt("ErrLimitExceeded"), indent)
			}
			if minElemSize > 0 {
				fmt.Fprintf(b, "%s\tif rawCount > uint64(len(src)-off)/%d {\n%s\t\treturn 0, %s\n%s\t}\n", indent, minElemSize, indent, g.rt("ErrShortBuffer"), indent)
			} else {
				fmt.Fprintf(b, "%s\tif rawCount > uint64(len(src)-off) && rawCount > 0 {\n%s\t\treturn 0, %s\n%s\t}\n", indent, indent, g.rt("ErrShortBuffer"), indent)
			}
			fmt.Fprintf(b, "%s\tcount := int(rawCount)\n%s\tif count == 0 {\n%s\t\t%s = %s[:0]\n%s\t} else {\n%s\t\tif cap(%s) < count {\n%s\t\t\t%s = make([]%s, count)\n%s\t\t} else {\n%s\t\t\t%s = %s[:count]\n%s\t\t}\n%s\t\tfor i := 0; i < count; i++ {\n",
				indent, indent, indent, target, target, indent, indent, target, indent, target, elemGoType, indent, indent, target, target, indent, indent)
			g.emitDecodeArrayElem(b, indent+"\t\t\t", a.Of, elemOrd, a.OfBits, fmt.Sprintf("%s[i]", target))
			fmt.Fprintf(b, "%s\t\t}\n%s\t}\n%s}\n", indent, indent, indent)
		}
	case "mask":
		ms := f.Mask
		maskType := ms.Type
		if maskType == "" {
			maskType = "u8"
		}
		maskOrd := g.effectiveOrder(ms.Order, f.Order, m.Order)
		maskField := "m." + goName + "Mask"
		maskBits, _ := maskTypeBits(maskType)
		g.emitDecodeInt(b, indent, maskType, maskOrd, 0, maskField)
		if len(ms.Fields) < maskBits {
			fmt.Fprintf(b, "%sif %s&^%sMaskValid != 0 {\n%s\treturn 0, %s\n%s}\n", indent, maskField, m.Name, indent, g.rt("ErrInvalidMask"), indent)
		}
		for _, sf := range ms.Fields {
			sfGoName := toExportedIdent(sf.Name)
			bitConst := fmt.Sprintf("%sField%s", m.Name, sfGoName)
			fmt.Fprintf(b, "%sif %s&%s != 0 {\n", indent, maskField, bitConst)
			if g.isBitPacked(sf, m.Order) {
				fmt.Fprintf(b, "%s\tbrMask := %s{Src: src, Off: off}\n", indent, g.rt("BitReader"))
				switch sf.Type {
				case "bits":
					fmt.Fprintf(b, "%s\tv, err := brMask.ReadBits(%d)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\tif err := brMask.Align(); err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\tm.%s = %s(v)\n%s\toff = brMask.Off\n",
						indent, sf.Bits, indent, indent, indent, indent, indent, indent, indent, sfGoName, goIntTypeForWire("bits", sf.Bits), indent)
				case "qfloat":
					qf := sf.QFloat
					fmt.Fprintf(b, "%s\tv, err := brMask.ReadBits(%d)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\tif err := brMask.Align(); err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\tm.%s = %s(uint32(v), %s, %s, %d)\n%s\toff = brMask.Off\n",
						indent, qf.Bits, indent, indent, indent, indent, indent, indent, indent, sfGoName, g.rt("DequantizeFloat"), formatFloat32Lit(qf.Min), formatFloat32Lit(qf.Max), qf.Bits, indent)
				}
			} else {
				g.emitDecodeField(b, indent+"\t", m, sf)
			}
			fmt.Fprintf(b, "%s} else {\n", indent)
			g.emitClearField(b, indent+"\t", sf, "m."+sfGoName)
			fmt.Fprintf(b, "%s}\n", indent)
		}
	default:
		if _, ok := g.env.enums[f.Type]; ok {
			fmt.Fprintf(b, "%s{\n%s\tn, err := Decode%s(src[off:], &%s)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\toff += n\n%s}\n",
				indent, indent, f.Type, target, indent, indent, indent, indent, indent)
		} else {
			fmt.Fprintf(b, "%s{\n%s\tn, err := Decode%s(src[off:], &%s)\n%s\tif err != nil {\n%s\t\treturn 0, err\n%s\t}\n%s\toff += n\n%s}\n",
				indent, indent, f.Type, target, indent, indent, indent, indent, indent)
		}
	}
}

func (g *goGen) emitDecodeArrayElem(b *bytes.Buffer, indent, elemType string, ord ByteOrder, elemBits int, target string) {
	switch elemType {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint":
		g.emitDecodeInt(b, indent, elemType, ord, elemBits, target)
	case "bool":
		fmt.Fprintf(b, "%sif len(src)-off < 1 {\n%s\treturn 0, %s\n%s}\n%sswitch src[off] {\n%scase 0:\n%s\t%s = false\n%scase 1:\n%s\t%s = true\n%sdefault:\n%s\treturn 0, %s\n%s}\n%soff++\n",
			indent, indent, g.rt("ErrShortBuffer"), indent, indent, indent, indent, target, indent, indent, target, indent, indent, g.rt("ErrInvalidBool"), indent, indent)
	case "f32":
		g.useStd("math")
		fmt.Fprintf(b, "%sif len(src)-off < 4 {\n%s\treturn 0, %s\n%s}\n%s%s = math.Float32frombits(%s.Uint32(src[off : off+4]))\n%soff += 4\n",
			indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	default:
		fmt.Fprintf(b, "%sn, err := Decode%s(src[off:], &%s)\n%sif err != nil {\n%s\treturn 0, err\n%s}\n%soff += n\n",
			indent, elemType, target, indent, indent, indent, indent)
	}
}

func (g *goGen) emitDecodeInt(b *bytes.Buffer, indent, wireType string, ord ByteOrder, bits int, target string) {
	switch wireType {
	case "u8":
		fmt.Fprintf(b, "%sif len(src)-off < 1 {\n%s\treturn 0, %s\n%s}\n%s%s = src[off]\n%soff++\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, indent)
	case "i8":
		fmt.Fprintf(b, "%sif len(src)-off < 1 {\n%s\treturn 0, %s\n%s}\n%s%s = int8(src[off])\n%soff++\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, indent)
	case "u16":
		fmt.Fprintf(b, "%sif len(src)-off < 2 {\n%s\treturn 0, %s\n%s}\n%s%s = %s.Uint16(src[off : off+2])\n%soff += 2\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "i16":
		fmt.Fprintf(b, "%sif len(src)-off < 2 {\n%s\treturn 0, %s\n%s}\n%s%s = int16(%s.Uint16(src[off : off+2]))\n%soff += 2\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "u32":
		fmt.Fprintf(b, "%sif len(src)-off < 4 {\n%s\treturn 0, %s\n%s}\n%s%s = %s.Uint32(src[off : off+4])\n%soff += 4\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "i32":
		fmt.Fprintf(b, "%sif len(src)-off < 4 {\n%s\treturn 0, %s\n%s}\n%s%s = int32(%s.Uint32(src[off : off+4]))\n%soff += 4\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "u64":
		fmt.Fprintf(b, "%sif len(src)-off < 8 {\n%s\treturn 0, %s\n%s}\n%s%s = %s.Uint64(src[off : off+8])\n%soff += 8\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "i64":
		fmt.Fprintf(b, "%sif len(src)-off < 8 {\n%s\treturn 0, %s\n%s}\n%s%s = int64(%s.Uint64(src[off : off+8]))\n%soff += 8\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "uvarint":
		g.useStd("encoding/binary")
		fmt.Fprintf(b, "%s{\n%s\tv, n := binary.Uvarint(src[off:])\n%s\tif n == 0 {\n%s\t\treturn 0, %s\n%s\t}\n%s\tif n < 0 {\n%s\t\treturn 0, %s\n%s\t}\n",
			indent, indent, indent, indent, g.rt("ErrShortBuffer"), indent, indent, indent, g.rt("ErrOverflow"), indent)
		switch bits {
		case 8:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v > math.MaxUint8 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = uint8(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		case 16:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v > math.MaxUint16 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = uint16(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		case 32:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v > math.MaxUint32 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = uint32(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		default:
			fmt.Fprintf(b, "%s\t%s = v\n", indent, target)
		}
		fmt.Fprintf(b, "%s\toff += n\n%s}\n", indent, indent)
	case "svarint":
		g.useStd("encoding/binary")
		fmt.Fprintf(b, "%s{\n%s\tv, n := binary.Varint(src[off:])\n%s\tif n == 0 {\n%s\t\treturn 0, %s\n%s\t}\n%s\tif n < 0 {\n%s\t\treturn 0, %s\n%s\t}\n",
			indent, indent, indent, indent, g.rt("ErrShortBuffer"), indent, indent, indent, g.rt("ErrOverflow"), indent)
		switch bits {
		case 8:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v < math.MinInt8 || v > math.MaxInt8 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = int8(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		case 16:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v < math.MinInt16 || v > math.MaxInt16 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = int16(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		case 32:
			g.useStd("math")
			fmt.Fprintf(b, "%s\tif v < math.MinInt32 || v > math.MaxInt32 {\n%s\t\treturn 0, %s\n%s\t}\n%s\t%s = int32(v)\n", indent, indent, g.rt("ErrOverflow"), indent, indent, target)
		default:
			fmt.Fprintf(b, "%s\t%s = v\n", indent, target)
		}
		fmt.Fprintf(b, "%s\toff += n\n%s}\n", indent, indent)
	}
}

func (g *goGen) emitDecodeLen(b *bytes.Buffer, indent, lenKind string, ord ByteOrder, target string) {
	switch lenKind {
	case "u8":
		fmt.Fprintf(b, "%sif len(src)-off < 1 {\n%s\treturn 0, %s\n%s}\n%s%s = uint64(src[off])\n%soff++\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, indent)
	case "u16":
		fmt.Fprintf(b, "%sif len(src)-off < 2 {\n%s\treturn 0, %s\n%s}\n%s%s = uint64(%s.Uint16(src[off : off+2]))\n%soff += 2\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "u32":
		fmt.Fprintf(b, "%sif len(src)-off < 4 {\n%s\treturn 0, %s\n%s}\n%s%s = uint64(%s.Uint32(src[off : off+4]))\n%soff += 4\n", indent, indent, g.rt("ErrShortBuffer"), indent, indent, target, g.binaryOrderExpr(ord), indent)
	case "uvarint":
		g.useStd("encoding/binary")
		fmt.Fprintf(b, "%sv, vn := binary.Uvarint(src[off:])\n%sif vn == 0 {\n%s\treturn 0, %s\n%s}\n%sif vn < 0 {\n%s\treturn 0, %s\n%s}\n%s%s = v\n%soff += vn\n",
			indent, indent, indent, g.rt("ErrShortBuffer"), indent, indent, indent, g.rt("ErrOverflow"), indent, indent, target, indent)
	}
}

func (g *goGen) emitClearField(b *bytes.Buffer, indent string, f Field, target string) {
	switch f.Type {
	case "bytes":
		fmt.Fprintf(b, "%s%s = %s[:0]\n", indent, target, target)
	case "array":
		if f.Array.Count == 0 {
			fmt.Fprintf(b, "%s%s = %s[:0]\n", indent, target, target)
		} else {
			fmt.Fprintf(b, "%s%s = %s{}\n", indent, target, g.goTypeForField(f))
		}
	case "string":
		fmt.Fprintf(b, "%s%s = \"\"\n", indent, target)
	case "bool":
		fmt.Fprintf(b, "%s%s = false\n", indent, target)
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint", "f32", "qfloat", "fixed", "bits":
		fmt.Fprintf(b, "%s%s = 0\n", indent, target)
	default:
		if _, ok := g.env.enums[f.Type]; ok {
			fmt.Fprintf(b, "%s%s = 0\n", indent, target)
		} else {
			fmt.Fprintf(b, "%s%s = %s{}\n", indent, target, f.Type)
		}
	}
}

func (g *goGen) emitDeltaHelpers(b *bytes.Buffer, m Message, maskField Field) {
	ms := maskField.Mask
	maskType := ms.Type
	if maskType == "" {
		maskType = "u8"
	}
	maskGoType := goIntTypeForWire(maskType, 0)
	maskGoField := toExportedIdent(maskField.Name) + "Mask"

	fmt.Fprintf(b, "// Diff%s returns the presence mask of fields in cur that differ from base, comparing float bit patterns and byte slices directly.\n", m.Name)
	fmt.Fprintf(b, "func Diff%s(base, cur *%s) %s {\n\tvar mask %s\n", m.Name, m.Name, maskGoType, maskGoType)
	for _, sf := range ms.Fields {
		sfName := toExportedIdent(sf.Name)
		bitConst := fmt.Sprintf("%sField%s", m.Name, sfName)
		g.emitDiffCheck(b, "\t", sf, "base."+sfName, "cur."+sfName, bitConst)
	}
	b.WriteString("\treturn mask\n}\n\n")

	fmt.Fprintf(b, "// Apply%s copies every masked field present in delta into dst, reusing dst slice capacities.\n", m.Name)
	fmt.Fprintf(b, "func Apply%s(dst, delta *%s) {\n", m.Name, m.Name)
	for _, sf := range ms.Fields {
		sfName := toExportedIdent(sf.Name)
		bitConst := fmt.Sprintf("%sField%s", m.Name, sfName)
		fmt.Fprintf(b, "\tif delta.%s&%s != 0 {\n", maskGoField, bitConst)
		g.emitApplyCopy(b, "\t\t", sf, "dst."+sfName, "delta."+sfName)
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n\n")
}

func (g *goGen) emitDiffCheck(b *bytes.Buffer, indent string, sf Field, baseExpr, curExpr, bitConst string) {
	switch sf.Type {
	case "f32", "qfloat":
		g.useStd("math")
		fmt.Fprintf(b, "%sif math.Float32bits(%s) != math.Float32bits(%s) {\n%s\tmask |= %s\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "fixed":
		g.useStd("math")
		fmt.Fprintf(b, "%sif math.Float64bits(%s) != math.Float64bits(%s) {\n%s\tmask |= %s\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "bytes":
		g.useStd("bytes")
		fmt.Fprintf(b, "%sif !bytes.Equal(%s, %s) {\n%s\tmask |= %s\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	case "array":
		if sf.Array.Count > 0 && sf.Array.Of != "f32" && g.isComparableType(sf.Array.Of) {
			fmt.Fprintf(b, "%sif %s != %s {\n%s\tmask |= %s\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
		} else {
			fmt.Fprintf(b, "%s{\n%s\tdiff := len(%s) != len(%s)\n%s\tfor i := 0; !diff && i < len(%s); i++ {\n", indent, indent, curExpr, baseExpr, indent, curExpr)
			if sf.Array.Of == "f32" {
				g.useStd("math")
				fmt.Fprintf(b, "%s\t\tdiff = math.Float32bits(%s[i]) != math.Float32bits(%s[i])\n", indent, curExpr, baseExpr)
			} else {
				fmt.Fprintf(b, "%s\t\tdiff = %s[i] != %s[i]\n", indent, curExpr, baseExpr)
			}
			fmt.Fprintf(b, "%s\t}\n%s\tif diff {\n%s\t\tmask |= %s\n%s\t}\n%s}\n", indent, indent, indent, bitConst, indent, indent)
		}
	default:
		fmt.Fprintf(b, "%sif %s != %s {\n%s\tmask |= %s\n%s}\n", indent, curExpr, baseExpr, indent, bitConst, indent)
	}
}

func (g *goGen) emitApplyCopy(b *bytes.Buffer, indent string, sf Field, dstExpr, srcExpr string) {
	switch sf.Type {
	case "bytes":
		fmt.Fprintf(b, "%sif len(%s) == 0 {\n%s\t%s = %s[:0]\n%s} else {\n%s\t%s = append(%s[:0], %s...)\n%s}\n",
			indent, srcExpr, indent, dstExpr, dstExpr, indent, indent, dstExpr, dstExpr, srcExpr, indent)
	case "array":
		if sf.Array.Count == 0 {
			fmt.Fprintf(b, "%sif len(%s) == 0 {\n%s\t%s = %s[:0]\n%s} else {\n%s\t%s = append(%s[:0], %s...)\n%s}\n",
				indent, srcExpr, indent, dstExpr, dstExpr, indent, indent, dstExpr, dstExpr, srcExpr, indent)
		} else {
			fmt.Fprintf(b, "%s%s = %s\n", indent, dstExpr, srcExpr)
		}
	default:
		fmt.Fprintf(b, "%s%s = %s\n", indent, dstExpr, srcExpr)
	}
}

func (g *goGen) emitUnion(b *bytes.Buffer, u Union) {
	d := u.Discriminator
	var tagGoType string
	switch d.Type {
	case "u8", "nibble":
		tagGoType = "uint8"
	case "u16":
		tagGoType = "uint16"
	case "uvarint":
		tagGoType = "uint64"
	}

	b.WriteString("const (\n")
	if d.Type == "nibble" {
		highGoName := toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "\t%s%s uint8 = %d\n", u.Name, highGoName, d.HighValue)
	}
	for _, c := range u.Cases {
		if c.Doc != "" {
			writeDocComment(b, "\t", c.Doc)
		}
		caseGoName := unionCaseGoName(c)
		fmt.Fprintf(b, "\t%sTag%s %s = %d\n", u.Name, caseGoName, tagGoType, c.Tag)
	}
	b.WriteString(")\n\n")

	if u.Doc != "" {
		writeDocComment(b, "", u.Doc)
	}
	fmt.Fprintf(b, "type %s struct {\n", u.Name)
	fmt.Fprintf(b, "\tTag %s\n", tagGoType)
	if d.Type == "nibble" {
		fmt.Fprintf(b, "\t%s uint8\n", toExportedIdent(nibbleHighName(d)))
	}
	for _, c := range u.Cases {
		fmt.Fprintf(b, "\t%s %s\n", unionCaseGoName(c), c.Message)
	}
	b.WriteString("}\n\n")

	ord := g.effectiveOrder(d.Order)
	// Append<Union>
	fmt.Fprintf(b, "// Append%s encodes the active case of m onto dst in wire format without allocating when dst has capacity.\n", u.Name)
	fmt.Fprintf(b, "func Append%s(dst []byte, m *%s) []byte {\n", u.Name, u.Name)
	if d.Type == "nibble" {
		hb := nibbleHighBits(d)
		lb := 8 - hb
		lowMask := (1 << lb) - 1
		highField := "m." + toExportedIdent(nibbleHighName(d))
		highConst := u.Name + toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "\thigh := %s\n", highField)
		if d.HighValue != 0 {
			fmt.Fprintf(b, "\tif high == 0 {\n\t\thigh = %s\n\t}\n", highConst)
		}
		fmt.Fprintf(b, "\tdst = append(dst, (high<<%d)|(m.Tag&0x%x))\n", lb, lowMask)
	} else {
		g.emitAppendInt(b, "\t", d.Type, ord, "m.Tag")
	}
	b.WriteString("\tswitch m.Tag {\n")
	for _, c := range u.Cases {
		caseGoName := unionCaseGoName(c)
		fmt.Fprintf(b, "\tcase %sTag%s:\n\t\tdst = Append%s(dst, &m.%s)\n", u.Name, caseGoName, c.Message, caseGoName)
	}
	b.WriteString("\t}\n\treturn dst\n}\n\n")

	// Decode<Union>
	fmt.Fprintf(b, "// Decode%s decodes one %s from src into caller-owned storage m without heap allocations once slices have capacity.\n", u.Name, u.Name)
	fmt.Fprintf(b, "func Decode%s(src []byte, m *%s) (int, error) {\n\toff := 0\n", u.Name, u.Name)
	if d.Type == "nibble" {
		hb := nibbleHighBits(d)
		lb := 8 - hb
		lowMask := (1 << lb) - 1
		highField := "m." + toExportedIdent(nibbleHighName(d))
		highConst := u.Name + toExportedIdent(nibbleHighName(d))
		fmt.Fprintf(b, "\tif len(src) < 1 {\n\t\treturn 0, %s\n\t}\n", g.rt("ErrShortBuffer"))
		fmt.Fprintf(b, "\thigh := src[0] >> %d\n\ttag := src[0] & 0x%x\n\t%s = high\n\tm.Tag = tag\n\toff = 1\n", lb, lowMask, highField)
		// Validate tag before version so non-matching tags report ErrInvalidTag, matching pkg/net's readReplHeader.
		b.WriteString("\tswitch tag {\n\tcase ")
		for i, c := range u.Cases {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(b, "%sTag%s", u.Name, unionCaseGoName(c))
		}
		fmt.Fprintf(b, ":\n\tdefault:\n\t\treturn 0, %s\n\t}\n", g.rt("ErrInvalidTag"))
		fmt.Fprintf(b, "\tif high != %s {\n\t\treturn 0, %s\n\t}\n", highConst, g.rt("ErrInvalidVersion"))
	} else {
		fmt.Fprintf(b, "\tvar tag %s\n", tagGoType)
		g.emitDecodeInt(b, "\t", d.Type, ord, 0, "tag")
		b.WriteString("\tm.Tag = tag\n")
	}
	b.WriteString("\tswitch tag {\n")
	for _, c := range u.Cases {
		caseGoName := unionCaseGoName(c)
		fmt.Fprintf(b, "\tcase %sTag%s:\n\t\tn, err := Decode%s(src[off:], &m.%s)\n\t\tif err != nil {\n\t\t\treturn 0, err\n\t\t}\n\t\treturn off + n, nil\n",
			u.Name, caseGoName, c.Message, caseGoName)
	}
	fmt.Fprintf(b, "\tdefault:\n\t\treturn 0, %s\n\t}\n}\n\n", g.rt("ErrInvalidTag"))
}

func unionCaseGoName(c UnionCase) string {
	if c.Name != "" {
		return toExportedIdent(c.Name)
	}
	return toExportedIdent(c.Message)
}

func isSignedWireInt(t string) bool {
	switch t {
	case "i8", "i16", "i32", "i64", "svarint":
		return true
	default:
		return false
	}
}

func (g *goGen) signedBoundsExpr(t string) (string, string) {
	g.useStd("math")
	switch t {
	case "i8":
		return "math.MinInt8", "math.MaxInt8"
	case "i16":
		return "math.MinInt16", "math.MaxInt16"
	case "i32":
		return "math.MinInt32", "math.MaxInt32"
	default:
		return "math.MinInt64", "math.MaxInt64"
	}
}

func (g *goGen) unsignedMaxExpr(t string) string {
	g.useStd("math")
	switch t {
	case "u8":
		return "math.MaxUint8"
	case "u16":
		return "math.MaxUint16"
	case "u32":
		return "math.MaxUint32"
	default:
		return "math.MaxUint64"
	}
}

func (g *goGen) isComparableType(t string) bool {
	switch t {
	case "u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "uvarint", "svarint", "bool", "f32", "string":
		return true
	}
	if _, ok := g.env.enums[t]; ok {
		return true
	}
	return false
}

func (g *goGen) minTypeWireSize(t string) int {
	switch t {
	case "u8", "i8", "bool", "uvarint", "svarint":
		return 1
	case "u16", "i16":
		return 2
	case "u32", "i32", "f32":
		return 4
	case "u64", "i64":
		return 8
	}
	if en, ok := g.env.enums[t]; ok {
		return g.minTypeWireSize(en.Type)
	}
	if sz, ok := g.minWireSizes[t]; ok {
		return sz
	}
	m, ok := g.env.messages[t]
	if !ok {
		return 1
	}
	// Mark 0 first to guard against cycles.
	g.minWireSizes[t] = 0
	total := 0
	bitRun := 0
	for _, f := range m.Fields {
		if g.isBitPacked(f, m.Order) {
			if f.Type == "bits" {
				bitRun += f.Bits
			} else {
				bitRun += f.QFloat.Bits
			}
			continue
		}
		if bitRun > 0 {
			total += (bitRun + 7) / 8
			bitRun = 0
		}
		switch f.Type {
		case "bytes", "string":
			switch f.Length {
			case "rest":
				// 0 minimum bytes
			case "", "uvarint", "u8":
				total++
			case "u16":
				total += 2
			case "u32":
				total += 4
			}
		case "array":
			if f.Array.Count > 0 {
				total += f.Array.Count * g.minTypeWireSize(f.Array.Of)
			} else {
				switch f.Array.Length {
				case "", "uvarint", "u8":
					total++
				case "u16":
					total += 2
				case "u32":
					total += 4
				}
			}
		case "mask":
			mt := f.Mask.Type
			if mt == "" {
				mt = "u8"
			}
			total += g.minTypeWireSize(mt)
		case "fixed":
			total += g.minTypeWireSize(f.Fixed.Type)
		case "qfloat":
			total += (f.QFloat.Bits + 7) / 8
		default:
			total += g.minTypeWireSize(f.Type)
		}
	}
	if bitRun > 0 {
		total += (bitRun + 7) / 8
	}
	g.minWireSizes[t] = total
	return total
}

func formatFloat32Lit(v float64) string {
	f := float32(v)
	if f == 0 {
		return "0"
	}
	return strconv.FormatFloat(float64(f), 'g', -1, 32)
}

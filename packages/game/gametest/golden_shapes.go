func (m affine) scale() float64 {
	s := math.Sqrt(math.Hypot(m.a, m.b) * math.Hypot(m.c, m.d))
	if math.IsNaN(s) || math.IsInf(s, 0) || s <= 0 {
		return 1
	}
	return s
}

func scaleDashPattern(dash []float64, scale float64) []float64 {
	if len(dash) == 0 {
		return nil
	}
	out := make([]float64, len(dash))
	for i, v := range dash {
		out[i] = v * scale
	}
	return out
}

func buildRoundRectSub(m affine, x, y, w, h, r float64) (pathSub, bool) {
	x, y, w, h = normalizeRect(x, y, w, h)
	if w <= 0 || h <= 0 {
		return pathSub{}, false
	}
	r = min(max(r, 0), min(w/2, h/2))
	if r <= 0 {
		p0x, p0y := m.apply(x, y)
		p1x, p1y := m.apply(x+w, y)
		p2x, p2y := m.apply(x+w, y+h)
		p3x, p3y := m.apply(x, y+h)
		return pathSub{pts: []pathPt{{p0x, p0y}, {p1x, p1y}, {p2x, p2y}, {p3x, p3y}}, closed: true}, true
	}
	const cornerSteps = 6
	pts := make([]pathPt, 0, 4*(cornerSteps+1))
	addCorner := func(cx, cy, a0, a1 float64) {
		for i := 0; i <= cornerSteps; i++ {
			a := a0 + (a1-a0)*float64(i)/float64(cornerSteps)
			px, py := m.apply(cx+r*math.Cos(a), cy+r*math.Sin(a))
			pts = append(pts, pathPt{x: px, y: py})
		}
	}
	addCorner(x+w-r, y+r, -math.Pi/2, 0)
	addCorner(x+w-r, y+h-r, 0, math.Pi/2)
	addCorner(x+r, y+h-r, math.Pi/2, math.Pi)
	addCorner(x+r, y+r, math.Pi, 1.5*math.Pi)
	return pathSub{pts: pts, closed: true}, true
}

func buildArcPoints(m affine, cx, cy, rx, ry, a0, a1 float64, ccw bool) []pathPt {
	if rx <= 0 || ry <= 0 {
		return nil
	}
	sweep := a1 - a0
	if ccw {
		if sweep > 0 {
			sweep -= 2 * math.Pi * math.Ceil(sweep/(2*math.Pi))
		}
	} else {
		if sweep < 0 {
			sweep += 2 * math.Pi * math.Ceil(-sweep/(2*math.Pi))
		}
	}
	if math.Abs(sweep) > 2*math.Pi {
		if ccw {
			sweep = -2 * math.Pi
		} else {
			sweep = 2 * math.Pi
		}
	}
	steps := max(12, min(64, int(math.Ceil(math.Abs(sweep)*max(rx, ry)*m.scale()/2))))
	pts := make([]pathPt, 0, steps+1)
	for i := 0; i <= steps; i++ {
		a := a0 + sweep*float64(i)/float64(steps)
		px, py := m.apply(cx+rx*math.Cos(a), cy+ry*math.Sin(a))
		pts = append(pts, pathPt{x: px, y: py})
	}
	return pts
}

func strokePolygonsDashed(dst *image.RGBA, subs []pathSub, lineWidth float64, dash []float64, sr, sg, sb, sa float64) {
	if len(dash) == 0 || lineWidth <= 0 {
		strokePolygons(dst, subs, lineWidth, sr, sg, sb, sa)
		return
	}
	var dashedSubs []pathSub
	for _, sub := range subs {
		n := len(sub.pts)
		if n < 2 {
			continue
		}
		segCount := n - 1
		if sub.closed {
			segCount = n
		}
		dashIdx := 0
		rem := dash[0]
		drawing := true
		var active []pathPt

		flush := func() {
			if len(active) >= 2 {
				dashedSubs = append(dashedSubs, pathSub{pts: active})
			}
			active = nil
		}

		for i := range segCount {
			p0 := sub.pts[i]
			p1 := sub.pts[(i+1)%n]
			dx, dy := p1.x-p0.x, p1.y-p0.y
			segLen := math.Hypot(dx, dy)
			if segLen <= 1e-9 {
				continue
			}
			pos := 0.0
			for pos < segLen-1e-9 {
				step := min(rem, segLen-pos)
				t0 := pos / segLen
				t1 := (pos + step) / segLen
				a := pathPt{x: p0.x + dx*t0, y: p0.y + dy*t0}
				b := pathPt{x: p0.x + dx*t1, y: p0.y + dy*t1}
				if drawing {
					if len(active) == 0 {
						active = append(active, a)
					}
					active = append(active, b)
				}
				pos += step
				rem -= step
				if rem <= 1e-9 {
					if drawing {
						flush()
					}
					dashIdx = (dashIdx + 1) % len(dash)
					rem = dash[dashIdx]
					drawing = !drawing
				}
			}
		}
		flush()
	}
	strokePolygons(dst, dashedSubs, lineWidth, sr, sg, sb, sa)
}


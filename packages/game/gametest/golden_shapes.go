func drawBitmapText(dst *image.RGBA, x, y int, text string, sr, sg, sb, sa float64, scale int) {
	b := dst.Bounds()
	w, h := b.Dx(), b.Dy()
	cx := x
	for _, ch := range text {
		glyph, ok := bitmapGlyph5x7[ch]
		if !ok {
			if ch >= 'a' && ch <= 'z' {
				glyph = bitmapGlyph5x7[ch-'a'+'A']
			} else {
				glyph = bitmapGlyph5x7[' ']
			}
		}
		for row := range 7 {
			bits := glyph[row]
			for col := range 5 {
				if bits&(1<<(4-col)) == 0 {
					continue
				}
				for dy := range scale {
					py := y + row*scale + dy
					if py < 0 || py >= h {
						continue
					}
					for dx := range scale {
						px := cx + col*scale + dx
						if px < 0 || px >= w {
							continue
						}
						blendOver(dst, px, py, sr, sg, sb, sa)
					}
				}
			}
		}
		cx += 6 * scale
	}
}

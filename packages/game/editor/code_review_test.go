func setupCodeReviewProject(t *testing.T) (string, *editor.Editor) {
	t.Helper()
	dir := t.TempDir()
	mustWrite := func(rel, content string) {
		t.Helper()
		full := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("mkdir %s: %v", rel, err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			t.Fatalf("write %s: %v", rel, err)
		}
	}
	mustWrite("go.mod", "module example.com/dungeonrun\n\ngo 1.24\n")
	mustWrite("game.yaml", "version: 1\nname: dungeon-run\nstartScene: scenes/level_02.scene.yaml\n")
	mustWrite("prefabs/slime.prefab.yaml", testPrefabOriginal)
	mustWrite("gameplay/patrol.go", testPatrolOriginal)

	ed := newTestEditor(t)
	ed.ProjectPath = filepath.Join(dir, "game.yaml")
	ed.ExternalEditorName = "GoLand"
	return dir, ed
}

// runRealGoOverlayChecks runs `go vet` and `go test -json -count=1` using the real Go build overlay
// generated by editor.BuildGoOverlay, proving pending Go files are verified without touching disk.
func runRealGoOverlayChecks(ctx context.Context, req editor.CodeReviewCheckRequest, onProgress func(editor.CodeReviewCheckProgress)) (editor.CodeReviewCheckResult, error) {
	started := time.Now()
	res := editor.CodeReviewCheckResult{
		Packages: req.Packages,
	}
	env := append(os.Environ(), "GOWORK=off", "GOFLAGS=-overlay="+req.OverlayPath)

	vetCmd := exec.CommandContext(ctx, "go", append([]string{"vet"}, req.Packages...)...)
	vetCmd.Dir = req.ProjectDir
	vetCmd.Env = env
	vetOut, vetErr := vetCmd.CombinedOutput()
	res.CheckOutput = strings.TrimSpace(string(vetOut))
	if vetErr != nil {
		res.CheckPassed = false
		res.CheckError = res.CheckOutput
		res.Phase = editor.CodeReviewChecksFailed
		res.Duration = time.Since(started)
		return res, nil
	}
	res.CheckPassed = true

	testCmd := exec.CommandContext(ctx, "go", append([]string{"test", "-json", "-count=1"}, req.Packages...)...)
	testCmd.Dir = req.ProjectDir
	testCmd.Env = env
	out, _ := testCmd.Output()
	res.TestPassed = true
	linesByTest := map[string][]string{}
	sc := bufio.NewScanner(strings.NewReader(string(out)))
	for sc.Scan() {
		var ev struct {
			Action string `json:"Action"`
			Test   string `json:"Test"`
			Output string `json:"Output"`
		}
		if json.Unmarshal(sc.Bytes(), &ev) != nil {
			continue
		}
		if ev.Test != "" && ev.Output != "" {
			linesByTest[ev.Test] = append(linesByTest[ev.Test], ev.Output)
		}
		if ev.Test == "" || strings.Contains(ev.Test, "/") {
			continue
		}
		switch ev.Action {
		case "pass":
			res.PassedCount++
			res.Completed++
			if onProgress != nil {
				onProgress(editor.CodeReviewCheckProgress{Completed: res.Completed, Total: max(req.PreviousTotal, res.Completed), CurrentTest: ev.Test})
			}
		case "fail":
			res.FailedCount++
			res.Completed++
			res.TestPassed = false
			msg := strings.TrimSpace(strings.Join(linesByTest[ev.Test], ""))
			file, line := "patrol_test.go", 12
			for _, l := range linesByTest[ev.Test] {
				tr := strings.TrimSpace(l)
				if strings.HasPrefix(tr, "patrol_test.go:") {
					msg = tr
					var ln int
					if _, err := fmt.Sscanf(tr, "patrol_test.go:%d:", &ln); err == nil && ln > 0 {
						line = ln
					}
					break
				}
			}
			res.Failures = append(res.Failures, editor.CodeReviewTestFailure{
				Package:  req.Packages[0],
				TestName: ev.Test,
				File:     file,
				Line:     line,
				Message:  msg,
			})
		}
	}
	res.TotalCount = res.PassedCount + res.FailedCount
	res.Duration = time.Since(started)
	if res.CheckPassed && res.TestPassed && res.FailedCount == 0 {
		res.Phase = editor.CodeReviewChecksPassed
	} else {
		res.Phase = editor.CodeReviewChecksFailed
	}
	return res, nil
}

// #1034: Pending Go changes run checks via a real Go build overlay without touching disk;
// Confirm is refused while tests fail; Round 2 fix inside the same turn passes and unlocks Confirm;
// Keep writes YAML + confirmed Go files in one undo step, and one Undo restores disk.
func TestCodeReviewBuildOverlayLeavesDiskUntouchedAndFailsThenPasses(t *testing.T) {
	if runtime.GOOS == "ios" || runtime.GOOS == "android" || runtime.GOOS == "js" {
		t.Skip("requires desktop Go toolchain")
	}
	dir, ed := setupCodeReviewProject(t)
	ed.CodeReviewCheckRunner = runRealGoOverlayChecks

	// Round 1: propose prefab edit + buggy patrol.go + brand-new patrol_test.go.
	if err := ed.ProposeCodeReviewFiles(editor.CodeReviewProposeRequest{
		Prompt:             "Slimes walk off the platform edges on level_02. Make them turn around at ledges.",
		FailureExplanation: "The new floor check on line 33 probes the row the slime stands on, so it finds no ground only after the slime has stepped off.",
		SuspectFile:        "gameplay/patrol.go",
		SuspectLine:        36,
		PlayImpact:         "Until you confirm it, slimes still walk off ledges in play.",
		Open:               true,
		Files: []editor.CodeReviewProposedFile{
			{Path: "prefabs/slime.prefab.yaml", Content: testPrefabPending, Note: "Part of Keep. Every slime prefab variant inherits it."},
			{Path: "gameplay/patrol.go", Content: testPatrolRound1Buggy},
			{Path: "gameplay/patrol_test.go", Content: testPatrolTestFile},
		},
	}); err != nil {
		t.Fatalf("ProposeCodeReviewFiles round 1: %v", err)
	}

	// Disk must remain completely unchanged before Keep.
	gotPatrol, _ := os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	if string(gotPatrol) != testPatrolOriginal {
		t.Fatalf("patrol.go on disk was modified before Keep")
	}
	if _, err := os.Stat(filepath.Join(dir, "gameplay/patrol_test.go")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("patrol_test.go should not exist on disk before Keep, stat err = %v", err)
	}

	// Run real Go build overlay checks -> TestSlimeTurnsAtLedge fails!
	if err := ed.RunCodeReviewChecks(context.Background()); err != nil {
		t.Fatalf("RunCodeReviewChecks round 1: %v", err)
	}
	sess := ed.CodeReviewSession()
	if sess.Checks.Phase != editor.CodeReviewChecksFailed {
		t.Fatalf("checks phase = %q, want failed", sess.Checks.Phase)
	}
	if !sess.Checks.CheckPassed || sess.Checks.TestPassed || sess.Checks.FailedCount != 1 || sess.Checks.PassedCount != 1 {
		t.Fatalf("unexpected check summary: %+v", sess.Checks)
	}
	fail := sess.Checks.PrimaryFailure()
	if fail == nil || fail.TestName != "TestSlimeTurnsAtLedge" || !strings.Contains(fail.Message, "walked off the ledge") {
		t.Fatalf("unexpected failure: %+v", fail)
	}

	// Confirm must be refused while checks fail.
	if err := ed.ConfirmCodeReviewFile("gameplay/patrol.go", true); !errors.Is(err, editor.ErrCodeReviewChecksNotPassed) {
		t.Fatalf("ConfirmCodeReviewFile while failed = %v, want ErrCodeReviewChecksNotPassed", err)
	}
	if ed.CanConfirmCodeReviewFile("gameplay/patrol.go") {
		t.Fatal("CanConfirmCodeReviewFile returned true while failing")
	}

	// Verify line 36 in patrol.go diff is tagged `fails test` and failing line in patrol_test.go is tagged `failed here`.
	var sawFailsTest, sawFailedHere bool
	for _, l := range sess.FindFile("gameplay/patrol.go").Diff {
		if l.NewLine == 36 && l.Tag == editor.CodeReviewTagFailsTest {
			sawFailsTest = true
		}
	}
	for _, l := range sess.FindFile("gameplay/patrol_test.go").Diff {
		if l.NewLine == fail.Line && l.Tag == editor.CodeReviewTagFailedHere {
			sawFailedHere = true
		}
	}
	if !sawFailsTest || !sawFailedHere {
		t.Fatalf("expected fails test (%v) and failed here (%v) tags", sawFailsTest, sawFailedHere)
	}

	// Ask the agent to fix -> stays in same turn, enters Round 2.
	turnID := sess.TurnID
	var fixReq editor.CodeReviewFixRequest
	ed.OnAskCodeReviewFix = func(r editor.CodeReviewFixRequest) { fixReq = r }
	if err := ed.AskAgentToFixCodeReview(); err != nil {
		t.Fatalf("AskAgentToFixCodeReview: %v", err)
	}
	if fixReq.TurnID != turnID || fixReq.Round != 2 || fixReq.Failure == nil {
		t.Fatalf("unexpected fix request: %+v", fixReq)
	}

	// Agent submits Round 2 fix inside the same turn.
	if err := ed.ProposeCodeReviewFiles(editor.CodeReviewProposeRequest{
		RoundSummary: "Round 2 changed one line: the probe now looks one pixel below the slime's feet.",
		PreserveTurn: true,
		Open:         true,
		Files: []editor.CodeReviewProposedFile{
			{Path: "gameplay/patrol.go", Content: testPatrolRound2Fixed},
		},
	}); err != nil {
		t.Fatalf("ProposeCodeReviewFiles round 2: %v", err)
	}
	if sess.TurnID != turnID || sess.Round != 2 {
		t.Fatalf("round 2 turn mismatch: turn=%q (want %q), round=%d", sess.TurnID, turnID, sess.Round)
	}
	if len(ed.AgentTurns()) != 1 {
		t.Fatalf("expected Round 2 to stay within 1 turn, got %d turns", len(ed.AgentTurns()))
	}

	// Rerun checks via overlay -> both tests pass!
	if err := ed.RunCodeReviewChecks(context.Background()); err != nil {
		t.Fatalf("RunCodeReviewChecks round 2: %v", err)
	}
	if sess.Checks.Phase != editor.CodeReviewChecksPassed || sess.Checks.PassedCount != 2 || sess.Checks.FailedCount != 0 {
		t.Fatalf("round 2 checks = %+v, want 2 passed", sess.Checks)
	}

	// Line 36 is now tagged `round 2`.
	sawRound2 := false
	for _, l := range sess.FindFile("gameplay/patrol.go").Diff {
		if l.NewLine == 36 && l.Tag == editor.CodeReviewTagRound2 {
			sawRound2 = true
		}
	}
	if !sawRound2 {
		t.Fatal("expected line 33 to carry round 2 tag after Round 2 checks passed")
	}

	// Confirm both Go files; disk is STILL untouched until Keep.
	if err := ed.ConfirmCodeReviewFile("gameplay/patrol.go", true); err != nil {
		t.Fatalf("Confirm patrol.go: %v", err)
	}
	if err := ed.ConfirmCodeReviewFile("gameplay/patrol_test.go", true); err != nil {
		t.Fatalf("Confirm patrol_test.go: %v", err)
	}
	gotPatrol, _ = os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	if string(gotPatrol) != testPatrolOriginal {
		t.Fatal("Confirm alone must not write patrol.go before Keep")
	}

	// Keep writes prefab + both confirmed Go files in ONE undo step.
	if err := ed.KeepCodeReview(); err != nil {
		t.Fatalf("KeepCodeReview: %v", err)
	}
	if ed.HasPendingCodeReview() {
		t.Fatal("expected pending code review to clear after keeping all files")
	}
	gotPrefab, _ := os.ReadFile(filepath.Join(dir, "prefabs/slime.prefab.yaml"))
	gotPatrol, _ = os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	gotTest, _ := os.ReadFile(filepath.Join(dir, "gameplay/patrol_test.go"))
	if string(gotPrefab) != testPrefabPending || string(gotPatrol) != testPatrolRound2Fixed || string(gotTest) != testPatrolTestFile {
		t.Fatal("KeepCodeReview did not write expected YAML and confirmed Go files to disk")
	}

	// One Undo restores the old prefab and patrol.go and removes new patrol_test.go.
	if !ed.Undo() {
		t.Fatal("Undo() returned false")
	}
	gotPrefab, _ = os.ReadFile(filepath.Join(dir, "prefabs/slime.prefab.yaml"))
	gotPatrol, _ = os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	if string(gotPrefab) != testPrefabOriginal || string(gotPatrol) != testPatrolOriginal {
		t.Fatal("one Undo did not restore original prefab and patrol.go")
	}
	if _, err := os.Stat(filepath.Join(dir, "gameplay/patrol_test.go")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("one Undo did not remove newly created patrol_test.go: stat err = %v", err)
	}

	// One Redo re-applies all three files.
	if !ed.Redo() {
		t.Fatal("Redo() returned false")
	}
	gotPatrol, _ = os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	if string(gotPatrol) != testPatrolRound2Fixed {
		t.Fatal("Redo did not re-apply patrol.go")
	}
}

// #1034: Keep with unconfirmed Go files writes only YAML changes and leaves the waiting card in the Agent panel.
func TestCodeReviewKeepWithUnconfirmedGoWritesYAMLOnlyAndLeavesWaitingCard(t *testing.T) {
	dir, ed := setupCodeReviewProject(t)
	ed.SetRightRailTab(editor.RightTabAgent)
	ed.NotifyAgentMCPConnected(editor.AgentClientInfo{ID: "c1", Name: "claude-code", Transport: "stdio"})
	ed.CodeReviewCheckRunner = func(_ context.Context, req editor.CodeReviewCheckRequest, _ func(editor.CodeReviewCheckProgress)) (editor.CodeReviewCheckResult, error) {
		return editor.CodeReviewCheckResult{
			Phase:       editor.CodeReviewChecksPassed,
			CheckPassed: true,
			TestPassed:  true,
			PassedCount: 42,
			TotalCount:  42,
			Duration:    3100 * time.Millisecond,
			Packages:    req.Packages,
		}, nil
	}

	if err := ed.ProposeCodeReviewFiles(editor.CodeReviewProposeRequest{
		Prompt:     "Slimes walk off ledges on level_02.",
		PlayImpact: "Until you confirm it, slimes still walk off ledges in play.",
		Open:       true,
		Files: []editor.CodeReviewProposedFile{
			{Path: "prefabs/slime.prefab.yaml", Content: testPrefabPending},
			{Path: "gameplay/patrol.go", Content: testPatrolRound2Fixed},
		},
	}); err != nil {
		t.Fatalf("ProposeCodeReviewFiles: %v", err)
	}
	if err := ed.RunCodeReviewChecks(context.Background()); err != nil {
		t.Fatalf("RunCodeReviewChecks: %v", err)
	}

	app := nsgotest.Start(t, func(cx *core.Scope) core.Node {
		return editor.EditorView(cx, ed)
	}, nsgotest.Size(1440, 900))
	app.Settle()

	if !app.Exists("id:code-review-screen") {
		t.Fatal("CodeReviewView did not render")
	}

	// Press Keep 1 of 1 without confirming patrol.go.
	app.Press("id:code-review-keep")
	app.Settle()

	// YAML file is written to disk, Go file is untouched.
	gotPrefab, _ := os.ReadFile(filepath.Join(dir, "prefabs/slime.prefab.yaml"))
	gotPatrol, _ := os.ReadFile(filepath.Join(dir, "gameplay/patrol.go"))
	if string(gotPrefab) != testPrefabPending {
		t.Fatal("Keep did not write slime.prefab.yaml")
	}
	if string(gotPatrol) != testPatrolOriginal {
		t.Fatal("Keep wrote unconfirmed patrol.go to disk")
	}

	// Agent panel shows the waiting card with Review patrol.go button.
	if !app.Exists("id:agent-go-waiting-card") {
		t.Fatal("Agent panel waiting card did not appear after Keep with unconfirmed Go")
	}
	title := agentViewText(t, app, "id:agent-go-waiting-title")
	if !strings.Contains(title, "patrol.go is waiting for your OK") {
		t.Fatalf("waiting card title = %q, want patrol.go is waiting for your OK", title)
	}
	body := agentViewText(t, app, "id:agent-go-waiting-body")
	if !strings.Contains(body, "slimes still walk off ledges in play") {
		t.Fatalf("waiting card body = %q, want play impact note", body)
	}

	// Clicking Review patrol.go reopens the Go review screen directly on patrol.go.
	app.Press("id:agent-go-waiting-review")
	app.Settle()
	if !ed.CodeReviewOpen() || !app.Exists("id:code-review-screen") {
		t.Fatal("Review patrol.go button did not reopen CodeReviewView")
	}
}


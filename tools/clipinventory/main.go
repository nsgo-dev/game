// Command clipinventory writes a deterministic Markdown inventory for rigged glTF models.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type document struct {
	Meshes []struct {
		Name       string `json:"name"`
		Primitives []struct {
			Attributes map[string]int `json:"attributes"`
		} `json:"primitives"`
	} `json:"meshes"`
	Skins []struct {
		Name   string `json:"name"`
		Joints []int  `json:"joints"`
	} `json:"skins"`
	Nodes []struct {
		Name string `json:"name"`
	} `json:"nodes"`
	Accessors []struct {
		Min []float64 `json:"min"`
		Max []float64 `json:"max"`
	} `json:"accessors"`
	Animations []struct {
		Name     string `json:"name"`
		Samplers []struct {
			Input int `json:"input"`
		} `json:"samplers"`
	} `json:"animations"`
}

type model struct {
	Path                 string
	Name                 string
	Meshes, Skins, Bones int
	Clips                []clip
}
type clip struct {
	Name     string
	Duration float64
}

func main() {
	var out string
	flag.StringVar(&out, "out", "README.md", "output Markdown file")
	flag.Parse()
	if flag.NArg() == 0 {
		fmt.Fprintln(os.Stderr, "clipinventory: pass one or more .gltf files")
		os.Exit(2)
	}
	models := make([]model, 0, flag.NArg())
	for _, path := range flag.Args() {
		m, err := readModel(path)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		models = append(models, m)
	}
	sort.Slice(models, func(i, j int) bool { return models[i].Name < models[j].Name })
	data := render(models)
	if err := os.WriteFile(out, []byte(data), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func render(models []model) string {
	models = append([]model(nil), models...)
	sort.Slice(models, func(i, j int) bool { return models[i].Name < models[j].Name })
	var b strings.Builder
	b.WriteString("# CC0 Adventurers\n\nGenerated by `go run ./tools/clipinventory -out README.md mage.gltf knight.gltf`. Both models are CC0-1.0 KayKit Adventurers assets trimmed to the same clip names.\n\n")
	for _, m := range models {
		fmt.Fprintf(&b, "## %s\n\n| Metric | Count |\n| --- | ---: |\n| Meshes | %d |\n| Skins | %d |\n| Bones | %d |\n\n| Clip | Duration (s) |\n| --- | ---: |\n", m.Name, m.Meshes, m.Skins, m.Bones)
		for _, c := range m.Clips {
			fmt.Fprintf(&b, "| `%s` | %.3f |\n", c.Name, c.Duration)
		}
		b.WriteString("\n")
	}
	return b.String()
}

func readModel(path string) (model, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return model{}, fmt.Errorf("%s: %w", path, err)
	}
	var d document
	if err := json.Unmarshal(raw, &d); err != nil {
		return model{}, fmt.Errorf("%s: %w", path, err)
	}
	m := model{Path: path, Name: strings.TrimSuffix(filepath.Base(path), filepath.Ext(path)), Meshes: len(d.Meshes), Skins: len(d.Skins)}
	for _, s := range d.Skins {
		m.Bones += len(s.Joints)
	}
	for _, a := range d.Animations {
		if len(a.Samplers) == 0 {
			continue
		}
		i := a.Samplers[0].Input
		if i < 0 || i >= len(d.Accessors) {
			return model{}, fmt.Errorf("%s: animation %q has invalid input accessor", path, a.Name)
		}
		acc := d.Accessors[i]
		if len(acc.Min) == 0 || len(acc.Max) == 0 {
			return model{}, fmt.Errorf("%s: animation %q input has no bounds", path, a.Name)
		}
		m.Clips = append(m.Clips, clip{Name: a.Name, Duration: acc.Max[0] - acc.Min[0]})
	}
	sort.Slice(m.Clips, func(i, j int) bool { return m.Clips[i].Name < m.Clips[j].Name })
	return m, nil
}
